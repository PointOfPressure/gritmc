//! Structure placement against a **real generated world**.
//!
//! `golden_structure_placement` compares this port against vanilla's
//! placement methods, called directly, over a square around the origin. This
//! compares it against something different in kind: the structures a real
//! vanilla server actually started, read out of the region files it wrote.
//!
//! Vanilla records `structures.starts` in each chunk's own NBT, so a
//! generated region is a free oracle for the structure stage — which chunks
//! a structure started in, and the bounding box, orientation and recursion
//! depth of every piece — with no JVM harness at all. The world used here is
//! the same one the whole-world parity diff scores against
//! (`ci/gen-vanilla-region.sh`, seed 20260722), so it costs nothing extra.
//!
//! # What this can and cannot say
//!
//! A start exists only where placement accepted the chunk **and** the
//! structure's biome filter passed **and** its generation point was found.
//! So this is a one-directional check: every start must be on a placement
//! chunk, but a placement chunk need not have a start. Asserting the
//! converse would be asserting the two things this port has not written yet.
//!
//! That still makes it worth having, and for two reasons the direct
//! comparison cannot cover:
//!
//! - **The coordinates are somewhere else.** The golden vector is a radius-48
//!   square around the origin; these starts are at chunks like (75, 55) and
//!   (-1, 13). The `Mth.getSeed` bug that started this project was invisible
//!   within ~686 blocks of spawn, and near-origin testing is how it survived.
//! - **It is the real pipeline.** Vanilla's own `createStructures` ran, with
//!   a live `ChunkGeneratorStructureState` — the object the golden dumper
//!   could not build, and therefore the path the other gate cannot reach.

use rustmc_world::anvil::read_region;
use rustmc_worldgen::structure::placement::StructurePlacement;

/// The vanilla worlds the whole-world diff scores against, as
/// `(region dir, seed)`.
///
/// Two of them, because one seed is one place: seed 31415926's mines are the
/// ones the r7 diff disagrees with, and a gate that only ever looked at
/// 20260722 reported 100% while 1,031 mineshaft blocks were wrong somewhere
/// else. Any world generated by `ci/gen-vanilla-region.sh` can be added here
/// and costs nothing extra, since the regions already exist for the diff.
const WORLDS: [(&str, i64); 3] = [
    (
        concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../oracle-work/t2-regiondiff/a"
        ),
        20_260_722,
    ),
    (
        concat!(env!("CARGO_MANIFEST_DIR"), "/../../oracle-work/vanilla-r7"),
        20_260_722,
    ),
    (
        concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../oracle-work/vanilla-s2-r7"
        ),
        31_415_926,
    ),
];
const REGION_DIR: &str = WORLDS[0].0;
const SEED: i64 = WORLDS[0].1;

const SETS_DIR: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../oracle-work/vanilla-26.2/generated-data/data/minecraft/worldgen/structure_set"
);

/// Which set owns each structure, and that set's placement.
fn owners() -> Option<std::collections::BTreeMap<String, (String, StructurePlacement)>> {
    let dir = std::path::Path::new(SETS_DIR);
    if !rustmc_data::fixture::available(dir, "structure-set extract", "ci/vanilla-server.sh data") {
        return None;
    }
    let mut out = std::collections::BTreeMap::new();
    for entry in std::fs::read_dir(dir).ok()? {
        let path = entry.ok()?.path();
        if path.extension().and_then(|e| e.to_str()) != Some("json") {
            continue;
        }
        let json: serde_json::Value =
            serde_json::from_str(&std::fs::read_to_string(&path).ok()?).ok()?;
        let set = format!("minecraft:{}", path.file_stem()?.to_str()?);
        let placement = StructurePlacement::parse(&json["placement"]).ok()?;
        for structure in json["structures"].as_array()? {
            out.insert(
                structure["structure"].as_str()?.to_string(),
                (set.clone(), placement.clone()),
            );
        }
    }
    Some(out)
}

#[test]
fn every_structure_a_real_world_started_is_on_a_placement_chunk() {
    let Some(owners) = owners() else { return };
    let dir = std::path::Path::new(REGION_DIR);
    if !rustmc_data::fixture::available(
        dir,
        "vanilla region at {REGION_DIR}",
        "ci/vanilla-server.sh data",
    ) {
        return;
    }

    let mut accepted = 0usize;
    let mut rejected = 0usize;
    let mut refused = 0usize;
    let mut by_structure: std::collections::BTreeMap<String, usize> = Default::default();
    let mut pieces_seen = 0usize;
    let mut chunks_read = 0usize;
    let mut failures: Vec<String> = Vec::new();

    for entry in std::fs::read_dir(dir).expect("readable") {
        let path = entry.expect("entry").path();
        if path.extension().and_then(|e| e.to_str()) != Some("mca") {
            continue;
        }
        for chunk in read_region(&path).expect("a readable region") {
            chunks_read += 1;
            for start in &chunk.structure_starts {
                // The entry records its own chunk; it must be the one it is
                // stored in. A disagreement means the reader is matching
                // starts to the wrong chunk, which would make every check
                // below meaningless rather than wrong.
                assert_eq!(
                    (start.chunk_x, start.chunk_z),
                    (chunk.x, chunk.z),
                    "{} claims to start at ({}, {}) but is stored in ({}, {})",
                    start.id,
                    start.chunk_x,
                    start.chunk_z,
                    chunk.x,
                    chunk.z
                );
                assert!(
                    !start.pieces.is_empty(),
                    "{} at ({}, {}) started with no pieces",
                    start.id,
                    chunk.x,
                    chunk.z
                );
                pieces_seen += start.pieces.len();
                *by_structure.entry(start.id.clone()).or_insert(0) += 1;

                let Some((set, placement)) = owners.get(&start.id) else {
                    panic!("{} is in no structure set", start.id);
                };
                match placement.is_structure_chunk_ignoring_exclusion(SEED, chunk.x, chunk.z) {
                    Ok(true) => accepted += 1,
                    Ok(false) => {
                        rejected += 1;
                        failures.push(format!(
                            "{} ({set}) started at ({}, {}) and this port says it cannot",
                            start.id, chunk.x, chunk.z
                        ));
                    }
                    Err(e) => {
                        refused += 1;
                        failures.push(format!("{} ({set}): {e:?}", start.id));
                    }
                }
            }
        }
    }

    for line in &failures {
        println!("  {line}");
    }
    println!(
        "REAL-WORLD STARTS: {accepted} accepted, {rejected} rejected, {refused} refused \
         over {chunks_read} chunks — {pieces_seen} pieces in {} structures",
        by_structure.len()
    );
    for (id, n) in &by_structure {
        println!("    {n:3}x {id}");
    }

    assert_eq!(rejected, 0, "see the list above");
    assert_eq!(refused, 0, "see the list above");
    // Coverage, so a world that stopped recording starts fails here rather
    // than reading a clean zero. Four structure types and a three-figure
    // piece count is what this world has; it may only go up.
    assert!(
        accepted >= 11,
        "only {accepted} starts found — is the region right?"
    );
    assert!(
        by_structure.len() >= 4,
        "only {} structure types: {by_structure:?}",
        by_structure.len()
    );
    assert!(pieces_seen >= 100, "only {pieces_seen} pieces");
}

/// The pieces themselves are recorded, and they are what the next stage has
/// to reproduce. Nothing compares them yet — this pins the *shape* of the
/// oracle so the port can be written against a known-good reading of it.
#[test]
fn the_recorded_pieces_are_usable_as_an_oracle() {
    let dir = std::path::Path::new(REGION_DIR);
    if !rustmc_data::fixture::available(
        dir,
        "vanilla region at {REGION_DIR}",
        "ci/vanilla-server.sh data",
    ) {
        return;
    }
    let mut mineshafts = 0usize;
    let mut kinds: std::collections::BTreeMap<String, usize> = Default::default();
    let mut deepest = 0i32;
    let mut biggest = 0usize;

    for entry in std::fs::read_dir(dir).expect("readable") {
        let path = entry.expect("entry").path();
        if path.extension().and_then(|e| e.to_str()) != Some("mca") {
            continue;
        }
        for chunk in read_region(&path).expect("a readable region") {
            for start in &chunk.structure_starts {
                if start.id != "minecraft:mineshaft" {
                    continue;
                }
                mineshafts += 1;
                biggest = biggest.max(start.pieces.len());
                for piece in &start.pieces {
                    *kinds.entry(piece.id.clone()).or_insert(0) += 1;
                    deepest = deepest.max(piece.depth);
                    let bb = piece.bounding_box;
                    assert!(
                        bb[0] <= bb[3] && bb[1] <= bb[4] && bb[2] <= bb[5],
                        "{}: inverted bounding box {bb:?}",
                        piece.id
                    );
                }
            }
        }
    }

    println!(
        "MINESHAFT ORACLE: {mineshafts} starts, biggest {biggest} pieces, \
         deepest recursion {deepest}"
    );
    for (kind, n) in &kinds {
        println!("    {n:4}x {kind}");
    }

    assert!(mineshafts > 0, "no mineshafts in this world");
    // Every piece carries a type, a box and a depth — the three things
    // `MineShaftPieces` has to get right. If any were missing the port would
    // be written against a reading that silently defaulted.
    assert!(
        kinds.len() >= 3,
        "only {} piece kinds: {kinds:?}",
        kinds.len()
    );
    assert!(deepest > 0, "no piece recorded a recursion depth");
    assert!(!kinds.contains_key(""), "a piece had no id");
}

/// **The layout gate.** Every piece of every mineshaft in a real world.
///
/// `Structure.GenerationContext.makeRandom` is
/// `WorldgenRandom(LegacyRandomSource(0)).setLargeFeatureSeed(seed, cx, cz)`,
/// so the stream a mineshaft is laid out from is reproducible from the seed
/// and the chunk alone — no world, no biomes, no neighbours. That is what
/// makes this comparable at all.
///
/// Compared per piece: the id, the full bounding box, the recorded
/// orientation and the recursion depth. Not just the count — a port that
/// produced the right number of the right kinds in the wrong places would
/// read green on a count.
#[test]
fn the_mineshaft_layout_matches_a_real_world() {
    use rustmc_worldgen::rng::legacy::LegacyRandomSource;
    use rustmc_worldgen::rng::worldgen_random::WorldgenRandom;
    use rustmc_worldgen::structure::mineshaft::MineshaftType;
    use rustmc_worldgen::structure::pieces::Facing;

    let mut mines = 0usize;
    let mut pieces_compared = 0usize;
    let mut pieces_wrong = 0usize;
    let mut count_mismatches = 0usize;
    let mut examples: Vec<String> = Vec::new();

    for (region_dir, seed) in WORLDS {
        let dir = std::path::Path::new(region_dir);
        if !rustmc_data::fixture::available(dir, "vanilla region", "ci/gen-vanilla-region.sh") {
            continue;
        }

        for entry in std::fs::read_dir(dir).expect("readable") {
            let path = entry.expect("entry").path();
            if path.extension().and_then(|e| e.to_str()) != Some("mca") {
                continue;
            }
            for chunk in read_region(&path).expect("a readable region") {
                for start in &chunk.structure_starts {
                    if start.id != "minecraft:mineshaft" {
                        continue;
                    }
                    mines += 1;
                    let mut random = WorldgenRandom::new(LegacyRandomSource::new(0));
                    random.set_large_feature_seed(seed, chunk.x, chunk.z);
                    let layout = rustmc_worldgen::structure::mineshaft::generate_with_kinds(
                        &mut random,
                        chunk.x,
                        chunk.z,
                        MineshaftType::Normal,
                        63,
                        -64,
                    )
                    .expect("a normal mineshaft");
                    let ours_kinds = &layout.kinds;
                    let ours = &layout.pieces;

                    if ours.len() != start.pieces.len() {
                        count_mismatches += 1;
                        examples.push(format!(
                            "({}, {}): {} pieces, vanilla has {}",
                            chunk.x,
                            chunk.z,
                            ours.len(),
                            start.pieces.len()
                        ));
                    }
                    for (i, want) in start.pieces.iter().enumerate() {
                        let Some(got) = ours.get(i) else { break };
                        pieces_compared += 1;
                        let got_facing = got.facing.map_or(-1, Facing::saved_value);
                        let bb = got.bounding_box;
                        // The corridor's own fields, which vanilla writes into the
                        // piece and a bounding box says nothing about. They decide
                        // the whole draw sequence: a spider corridor spends an
                        // entire `generateMaybeBox` that a plain one does not, and
                        // every draw after it moves. Comparing only boxes reported
                        // 100% while 1,031 mineshaft blocks were wrong.
                        let fields_same = match ours_kinds.get(i) {
                            Some(rustmc_worldgen::structure::mineshaft::Kind::Corridor {
                                has_rails,
                                spider,
                                sections,
                            }) => {
                                want.has_rails.is_none_or(|w| w == *has_rails)
                                    && want.spider.is_none_or(|w| w == *spider)
                                    && want.sections.is_none_or(|w| w == *sections)
                            }
                            // Not a corridor: vanilla writes none of these, and a
                            // piece that carries them anyway is itself a mismatch.
                            _ => {
                                want.has_rails.is_none()
                                    && want.spider.is_none()
                                    && want.sections.is_none()
                            }
                        };
                        let same = got.id == want.id
                            && [bb.min_x, bb.min_y, bb.min_z, bb.max_x, bb.max_y, bb.max_z]
                                == want.bounding_box
                            && got_facing == want.orientation
                            && got.depth == want.depth
                            && fields_same;
                        if !same {
                            pieces_wrong += 1;
                            if examples.len() < 8 {
                                examples.push(format!(
                                    "({}, {}) piece {i}: got {} {:?} o={got_facing} d={} \
                                 — want {} {:?} o={} d={}",
                                    chunk.x,
                                    chunk.z,
                                    got.id,
                                    [bb.min_x, bb.min_y, bb.min_z, bb.max_x, bb.max_y, bb.max_z],
                                    got.depth,
                                    want.id,
                                    want.bounding_box,
                                    want.orientation,
                                    want.depth
                                ));
                            }
                        }
                    }
                }
            }
        }
    }

    for line in &examples {
        println!("  {line}");
    }
    #[expect(
        clippy::cast_precision_loss,
        reason = "a percentage over a piece count"
    )]
    let exactness = if pieces_compared == 0 {
        0.0
    } else {
        100.0 * (pieces_compared - pieces_wrong) as f64 / pieces_compared as f64
    };
    println!(
        "MINESHAFT LAYOUT {exactness:.6}% over {pieces_compared} pieces \
         ({pieces_wrong} wrong) in {mines} mineshafts, {count_mismatches} with the wrong count"
    );

    assert!(mines >= 5, "only {mines} mineshafts");
    assert_eq!(count_mismatches, 0, "see above");
    assert_eq!(pieces_wrong, 0, "see above");
}

/// Placement and starts coincide **exactly** for mineshafts in this region.
///
/// The gate above is one-directional by necessity — a start proves placement
/// accepted the chunk, not the converse, because the biome filter and the
/// generation point also have to pass. Measured over this region, though,
/// they reject nothing: 5 placement chunks, 5 starts, none without.
///
/// So the converse *is* assertable here, and it is worth asserting because
/// it fails in the direction the other gate cannot see — a placement that
/// started accepting too many chunks. It is not a proof of the biome filter
/// or the weighted selection; it is the statement that neither rejected
/// anything in this world, which is what makes the equivalence hold. When
/// they are ported, this is the gate that will catch them getting it wrong.
#[test]
fn mineshaft_placement_and_starts_coincide_in_this_region() {
    let Some(owners) = owners() else { return };
    let dir = std::path::Path::new(REGION_DIR);
    if !rustmc_data::fixture::available(
        dir,
        "vanilla region at {REGION_DIR}",
        "ci/vanilla-server.sh data",
    ) {
        return;
    }
    let (_, mineshafts) = owners.get("minecraft:mineshaft").expect("mineshafts");

    let mut placement_chunks = 0usize;
    let mut starts = 0usize;
    let mut accepted_without_a_start: Vec<(i32, i32)> = Vec::new();

    for entry in std::fs::read_dir(dir).expect("readable") {
        let path = entry.expect("entry").path();
        if path.extension().and_then(|e| e.to_str()) != Some("mca") {
            continue;
        }
        for chunk in read_region(&path).expect("readable") {
            let has_start = chunk
                .structure_starts
                .iter()
                .any(|s| s.id.starts_with("minecraft:mineshaft"));
            if has_start {
                starts += 1;
            }
            if mineshafts
                .is_structure_chunk_ignoring_exclusion(SEED, chunk.x, chunk.z)
                .expect("random spread")
            {
                placement_chunks += 1;
                if !has_start {
                    accepted_without_a_start.push((chunk.x, chunk.z));
                }
            }
        }
    }

    println!(
        "MINESHAFT PLACEMENT vs STARTS: {placement_chunks} placement chunks, {starts} starts, \
         {} accepted without one",
        accepted_without_a_start.len()
    );
    assert_eq!(
        accepted_without_a_start,
        Vec::new(),
        "this port says a mineshaft may start in chunks where vanilla started none"
    );
    assert_eq!(
        placement_chunks, starts,
        "the two must agree in both directions"
    );
    assert!(
        placement_chunks >= 5,
        "only {placement_chunks} — is the region right?"
    );
}
