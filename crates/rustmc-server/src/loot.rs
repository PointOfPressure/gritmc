//! The server's one `rustmc_loot::Loot`, and the smelting map an entity table
//! needs.
//!
//! # This is the crate's first call site, and that is the finding
//!
//! `crates/rustmc-loot`'s own header says it plainly: *"It is inert until
//! something calls it. No call site exists yet."* Until this file,
//! `rustmc-server` did not even depend on the crate — 23 opcodes, 17,943 of
//! 18,003 golden vectors and a dispatch for 1,015 blocks, reachable from
//! nothing a client could do. A parity figure taken over a subsystem no
//! server path enters is a statement about the interpreter, not about the
//! server, and it is worth saying which of the two any later number is.
//!
//! What this file adds is the **entity** half only. Block drops still have no
//! call site: breaking a block on this server produces no item, and wiring
//! that is `useblock`'s to do rather than this lane's.
//!
//! # The tables, and what a missing one means
//!
//! Three fixtures, all generated by `ci/loot-golden.sh` and registered in
//! `ci/gen-gameplay-tables.sh`, plus `data/vanilla/recipes.json` from
//! `ci/dump-recipes.sh` for the smelting map. Every path is written as a
//! **whole literal**, because `ci/gen-gameplay-tables.sh` derives the set of
//! tables a tree must generate by grepping for the string
//! `"data/vanilla/<name>.json"` — a path assembled from a directory and a
//! filename is outside that set and its fixture then exists in exactly one
//! worktree on the box.
//!
//! A missing table makes [`shared`] answer `None`, which every caller must
//! treat as **refuse**, never as "drops nothing". That distinction is the
//! whole of `rustmc_loot::NoDrops`' design and it survives here.

use std::collections::BTreeMap;
use std::sync::{Arc, OnceLock};

use rustmc_loot::Loot;
use serde_json::Value;

/// `ci/loot-golden.sh`'s table corpus — 1,355 documents keyed by their table
/// id with the `minecraft:` prefix stripped.
pub const TABLES_PATH: &str = "data/vanilla/loot_tables.json";
/// `ci/loot-golden.sh`'s item tags — the `#minecraft:swords` and
/// `#minecraft:smelts_loot` references a predicate resolves.
pub const ITEM_TAGS_PATH: &str = "data/vanilla/item_tags.json";
/// `ci/loot-golden.sh`'s `BlockBehaviour.getLootTable()` mapping.
pub const BLOCK_MAP_PATH: &str = "data/vanilla/block_loot_map.json";
/// `ci/dump-recipes.sh`'s recipe corpus, for the smelting map.
pub const RECIPES_PATH: &str = "data/vanilla/recipes.json";

/// The dispatch plus the smelting map, loaded once.
#[derive(Debug)]
pub struct ServerLoot {
    loot: Loot,
    smelting: Arc<BTreeMap<String, String>>,
    enchantment_tags: Arc<BTreeMap<String, Vec<String>>>,
}

impl ServerLoot {
    /// The `Loot` dispatch.
    #[must_use]
    pub const fn dispatch(&self) -> &Loot {
        &self.loot
    }

    /// `RecipeType.SMELTING` as input id -> result id.
    #[must_use]
    pub fn smelting(&self) -> Arc<BTreeMap<String, String>> {
        Arc::clone(&self.smelting)
    }

    /// `minecraft:enchantment` tags, and **this server has none**.
    ///
    /// `#minecraft:smelts_loot` — the one enchantment tag the entity loot
    /// family names — lives in `data/minecraft/tags/enchantment/` and
    /// `ci/loot-golden.sh` dumps **item** tags only, so `item_tags.json` does
    /// not carry it. An empty map here is not a shrug: `EnchantmentPredicate`
    /// only reaches a tag lookup for a stack that HAS enchantments, and
    /// `crate::item::ItemStack` carries an item name and a count and no
    /// components at all. So the map is unreachable today and refuses
    /// honestly the moment it is not — which is the behaviour a fabricated
    /// tag map would have removed.
    #[must_use]
    pub fn enchantment_tags(&self) -> Arc<BTreeMap<String, Vec<String>>> {
        Arc::clone(&self.enchantment_tags)
    }
}

/// `RecipeType.SMELTING`, from the recipe corpus.
///
/// # What is deliberately narrow here
///
/// `SmeltItemFunction` builds a `SingleRecipeInput` and asks
/// `RecipeManager.getRecipeFor(SMELTING, input, level)`, which matches the
/// recipe's `Ingredient` — a stack, a list of stacks, or a `#tag`. This map
/// keys only the **single-item string** form, because that is what every
/// smelting recipe in the jar uses for a mob drop and because a tag-keyed
/// entry would need the item-tag map here as well.
///
/// A recipe this cannot key is therefore **absent** from the map, and an
/// absent entry is vanilla's own "no smelting recipe" path: the stack passes
/// through unchanged. So the failure mode of narrowing is a raw drop, which
/// is visible, rather than a wrong cooked one, which is not. The count is
/// returned so a caller can assert it rather than trust it.
///
/// `count` on the result is carried because `SmeltItemFunction` multiplies by
/// `result.getCount()`; every smelting recipe in this jar has count 1, and a
/// map that silently assumed so would be wrong the first time one does not.
fn smelting_map(recipes: &Value) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    let Some(obj) = recipes.as_object() else {
        return out;
    };
    for r in obj.values() {
        if r.get("type").and_then(Value::as_str) != Some("minecraft:smelting") {
            continue;
        }
        let (Some(input), Some(result)) = (
            r.get("ingredient").and_then(Value::as_str),
            r.get("result")
                .and_then(|v| v.get("id"))
                .and_then(Value::as_str),
        ) else {
            continue;
        };
        // `RecipeManager.getRecipeFor` returns the FIRST match in its own
        // order and this is a map, so a second recipe for one input would
        // silently replace the first. Keeping the first insertion is not
        // "the same answer as vanilla" — it is a different arbitrary one —
        // so the collision is left visible by not overwriting, and
        // `smelting_len` lets a test assert the count the jar has.
        out.entry(input.to_string())
            .or_insert_with(|| result.to_string());
    }
    out
}

fn load(rel: &str) -> Option<Value> {
    let text = std::fs::read_to_string(rel).ok()?;
    serde_json::from_str(&text).ok()
}

fn build() -> Option<ServerLoot> {
    let tables: BTreeMap<String, Value> = serde_json::from_value(load(TABLES_PATH)?).ok()?;
    let item_tags: BTreeMap<String, Vec<String>> =
        serde_json::from_value(load(ITEM_TAGS_PATH)?).ok()?;
    let block_map: BTreeMap<String, Option<String>> =
        serde_json::from_value(load(BLOCK_MAP_PATH)?).ok()?;
    // The recipes are a separate refusal: a tree with the loot tables and no
    // recipes can still roll every entity table that does not smelt, and
    // making the whole dispatch absent for it would be a wider refusal than
    // the missing data justifies. An empty map is vanilla's "no recipe"
    // path — see `smelting_map` — so this is the one `unwrap_or_default`
    // here that is a behaviour and not a shrug.
    let smelting = load(RECIPES_PATH)
        .map(|r| smelting_map(&r))
        .unwrap_or_default();
    Some(ServerLoot {
        loot: Loot::new(Arc::new(tables), Arc::new(item_tags), block_map),
        smelting: Arc::new(smelting),
        enchantment_tags: Arc::new(BTreeMap::new()),
    })
}

/// The shared dispatch, or `None` when a fixture is absent.
///
/// **`None` means refuse.** A caller that treated it as an empty drop would
/// turn a missing extract into a silently lootless server, which is this
/// project's central defect class wearing a data hat.
pub fn shared() -> Option<&'static ServerLoot> {
    static S: OnceLock<Option<ServerLoot>> = OnceLock::new();
    S.get_or_init(build).as_ref()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The smelting map is built from the `minecraft:smelting` rows and from
    /// nothing else — a `smoking` or `campfire_cooking` row with the same
    /// ingredient must not reach it, because `SmeltItemFunction` names
    /// `RecipeType.SMELTING` specifically.
    ///
    /// Raw porkchop is the case the pig's table depends on and all three
    /// types exist for it in the jar, so it is the row this asserts.
    #[test]
    fn only_the_smelting_type_reaches_the_map() {
        let doc = serde_json::json!({
            "cooked_porkchop": {
                "type": "minecraft:smelting",
                "ingredient": "minecraft:porkchop",
                "result": {"id": "minecraft:cooked_porkchop"}
            },
            "cooked_porkchop_from_smoking": {
                "type": "minecraft:smoking",
                "ingredient": "minecraft:porkchop",
                "result": {"id": "minecraft:wrong"}
            },
            "cooked_beef_from_campfire_cooking": {
                "type": "minecraft:campfire_cooking",
                "ingredient": "minecraft:beef",
                "result": {"id": "minecraft:cooked_beef"}
            }
        });
        let map = smelting_map(&doc);
        assert_eq!(
            map.get("minecraft:porkchop").map(String::as_str),
            Some("minecraft:cooked_porkchop")
        );
        assert!(
            !map.contains_key("minecraft:beef"),
            "campfire_cooking is not RecipeType.SMELTING"
        );
        assert_eq!(map.len(), 1);
    }

    /// A tag or list ingredient is skipped rather than mis-keyed, and the
    /// skip is an absence — which is vanilla's "no smelting recipe" path and
    /// leaves the drop raw.
    #[test]
    fn a_non_string_ingredient_is_skipped_and_not_mis_keyed() {
        let doc = serde_json::json!({
            "a": {
                "type": "minecraft:smelting",
                "ingredient": "#minecraft:logs",
                "result": {"id": "minecraft:charcoal"}
            },
            "b": {
                "type": "minecraft:smelting",
                "ingredient": ["minecraft:iron_ore", "minecraft:deepslate_iron_ore"],
                "result": {"id": "minecraft:iron_ingot"}
            }
        });
        let map = smelting_map(&doc);
        assert_eq!(
            map.get("#minecraft:logs").map(String::as_str),
            Some("minecraft:charcoal"),
            "a tag key is kept verbatim; it simply never matches a bare item id"
        );
        assert!(
            !map.values().any(|v| v == "minecraft:iron_ingot"),
            "a list ingredient has no single key and is skipped"
        );
    }
}
