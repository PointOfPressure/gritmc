/// The window half-width, in chunks, around the centre of each harvest's
/// interior.
///
/// **Two by default, eight for the published figure.** `ci/t0.sh` runs the
/// test suite in a DEBUG build, where the engine is roughly twenty times
/// slower, and a gate that costs minutes to re-measure a number nobody reads
/// on every branch is a tax rather than a check. The headline is taken
/// explicitly:
///
/// ```text
///   RUSTMC_LIGHT_HARVEST_RADIUS=8 cargo test --release -p rustmc-server \
///       --test light_harvest -- --nocapture
/// ```
///
/// The radius is not a tolerance — the comparison is exact at every radius
/// that fits — so a smaller window costs coverage and not correctness, and
/// the figure printed always names the radius it was taken at.
fn radius() -> i32 {
    std::env::var("RUSTMC_LIGHT_HARVEST_RADIUS")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(2)
}

struct Harvest {
    chunks: BTreeMap<(i32, i32), rustmc_world::anvil::ChunkColumn>,
}

/// Decoded harvests, memoised for the life of the test binary.
///
/// Not an optimisation for its own sake: reading and decoding all eight
/// region files of `vanilla-r7` is 2,210 chunks, the three harvests together
/// are ~5,500, and the tests here load each of them three or four times. In a
/// DEBUG build — which is how `ci/t0.sh` runs the suite — that decoding was
/// **2m37s of the run, more than the lighting itself**.
fn load_harvest(rel: &str) -> std::sync::Arc<Harvest> {
    static CACHE: std::sync::OnceLock<std::sync::Mutex<BTreeMap<String, std::sync::Arc<Harvest>>>> =
        std::sync::OnceLock::new();
    let cache = CACHE.get_or_init(|| std::sync::Mutex::new(BTreeMap::new()));
    if let Some(h) = cache.lock().expect("harvest cache").get(rel) {
        return std::sync::Arc::clone(h);
    }
    let h = std::sync::Arc::new(read_harvest(rel));
    cache
        .lock()
        .expect("harvest cache")
        .insert(rel.to_owned(), std::sync::Arc::clone(&h));
    h
}

fn read_harvest(rel: &str) -> Harvest {
    let dir = repo(rel);
    assert!(
        dir.is_dir(),
        "{}: no harvest — run ci/t0-remote.sh, which links oracle-work in. \
         This test does not skip: a light comparison that quietly measures \
         nothing is the defect this repo exists to avoid.",
        dir.display()
    );
    let mut chunks = BTreeMap::new();
    let mut entries: Vec<_> = std::fs::read_dir(&dir)
        .expect("harvest directory")
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "mca"))
        .collect();
    entries.sort();
    for path in entries {
        for c in rustmc_world::anvil::read_region(&path).expect("region file") {
            if c.status == "minecraft:full" && c.is_light_on && !c.light.is_empty() {
                chunks.insert((c.x, c.z), c);
            }
        }
    }
    assert!(
        !chunks.is_empty(),
        "the harvest holds no lit full chunks — nothing to compare"
    );
    Harvest { chunks }
}

/// The centre of the largest run of interior chunks, so the window is inside
/// real terrain rather than at the harvest's ragged edge.
fn window(h: &Harvest, r: i32) -> Option<(i32, i32)> {
    let present: BTreeSet<(i32, i32)> = h.chunks.keys().copied().collect();
    let interior: Vec<(i32, i32)> = present
        .iter()
        .copied()
        .filter(|&(x, z)| (-1..=1).all(|dx| (-1..=1).all(|dz| present.contains(&(x + dx, z + dz)))))
        .collect();
    assert!(!interior.is_empty(), "no interior chunk in the harvest");
    // The candidate whose whole (r+1) apron is loaded, nearest the interior
    // centroid — a deterministic choice, not an arbitrary one.
    let cx = interior.iter().map(|c| c.0).sum::<i32>() / i32::try_from(interior.len()).expect("n");
    let cz = interior.iter().map(|c| c.1).sum::<i32>() / i32::try_from(interior.len()).expect("n");
    let mut best: Option<((i32, i32), i32)> = None;
    for &(x, z) in &interior {
        let ok = (-r - 1..=r + 1)
            .all(|dx| (-r - 1..=r + 1).all(|dz| present.contains(&(x + dx, z + dz))));
        if !ok {
            continue;
        }
        let d = (x - cx).pow(2) + (z - cz).pow(2);
        if best.is_none_or(|(_, bd)| d < bd) {
            best = Some(((x, z), d));
        }
    }
    best.map(|(c, _)| c)
}

/// The largest radius up to `want` for which this harvest has a full apron,
/// with the window it names. A harvest smaller than the requested window is a
/// fact about the harvest, not a reason to refuse; a harvest with no window
/// at all is.
fn largest_window(h: &Harvest, want: i32) -> (i32, (i32, i32)) {
    for r in (0..=want).rev() {
        if let Some(c) = window(h, r) {
            return (r, c);
        }
    }
    panic!("no chunk in this harvest has all eight neighbours loaded")
}

struct Figure {
    nibbles: usize,
    differing: usize,
    scored_chunks: usize,
    per_layer: [usize; 2],
    /// The figure's own blind spot, and the sharpest thing that can be said
    /// about it.
    ///
    /// A saved region file carries `BlockLight`/`SkyLight` for a section only
    /// when that section's layer was **materialised** — a homogeneous layer
    /// is not written and the client recomputes it. So most section/layer
    /// pairs in the window carry no array and are unscorable, and a bare
    /// "we put light there" count would be meaningless: above the terrain we
    /// SHOULD put 15 everywhere and vanilla saved nothing.
    ///
    /// What is meaningful is whether **our** layer is uniform in exactly the
    /// pairs vanilla declined to save, because that is the property that made
    /// vanilla decline. A non-uniform layer where vanilla saved nothing is a
    /// place the residual could be hiding.
    unscored_pairs: usize,
    unscored_non_uniform: usize,
    /// `(section Y, vanilla, ours) -> count`, so a residual is attributed
    /// rather than described. ORACLE rule 9: measurements move suspects.
    census: BTreeMap<(i32, u8, u8), usize>,
    /// `RUSTMC_LIGHT_HARVEST_PROBE` — how many of vanilla's nibbles in the
    /// bottom padding section equal our converged value at the bottom y-slice
    /// of the section above, i.e. what `repeatFirstLayer` would have copied
    /// had it run after convergence.
    probe_total: usize,
    probe_matches_repeat: usize,
}

fn compare(d: &Dimension, emit: Option<&str>) -> Figure {
    let dg = dimension_geometry(d);
    let (mut props, ids) = load_props();
    if let Some(name) = emit {
        // The positive control: one state's emission is moved, and the figure
        // must move with it.
        let state = *ids
            .get(name)
            .unwrap_or_else(|| panic!("block_props.json has no state {name}"));
        props.emission[state as usize] = 15;
    }
    let air = *ids.get("minecraft:air").expect("air");
    let h = load_harvest(d.dir);
    let (r, (wx, wz)) = largest_window(&h, radius());

    // Load the apron too: the engine lights it, and only the inner window is
    // scored.
    let mut chunks = BTreeMap::new();
    let mut geometry: Option<LightGeometry> = None;
    let mut min_sy = i32::MAX;
    let mut max_sy = i32::MIN;
    for dx in -r - 1..=r + 1 {
        for dz in -r - 1..=r + 1 {
            let c = &h.chunks[&(wx + dx, wz + dz)];
            // The section extent must be taken over the LIGHT sections too,
            // not just the ones with `block_states`. The padding section
            // above the world and the one below it hold nothing but light,
            // `read_region` drops them from `sections`, and taking the extent
            // from `sections` alone gives `min_section_y = -3` where vanilla
            // has -4 — which silently clips section -5 out of the stored set
            // and out of the scoring at the same time, so the figure comes
            // back clean over a window one section short at each end. Caught
            // by the light-section-count cross-check below, which is exactly
            // what it is for.
            for sy in c.light.keys() {
                min_sy = min_sy.min(i32::from(*sy));
                max_sy = max_sy.max(i32::from(*sy));
            }
            let mut lc = LitChunk::default();
            for s in &c.sections {
                let sy = i32::from(s.y);
                min_sy = min_sy.min(sy);
                max_sy = max_sy.max(sy);
                let mut blocks = Vec::with_capacity(4096);
                for i in 0..4096usize {
                    let idx = if s.blocks.is_empty() {
                        0
                    } else {
                        usize::from(s.blocks[i])
                    };
                    let name = &s.palette[idx];
                    let id = *ids.get(name).unwrap_or_else(|| {
                        panic!("block_props.json has no state {name}, which the harvest uses")
                    });
                    blocks.push(id);
                }
                // An all-air section is not a section, for the engine's
                // purposes: `LevelChunkSection.hasOnlyAir()` is the predicate
                // `updateSectionStatus` is given, and a saved region file
                // stores air sections that vanilla would never declare.
                if blocks.iter().any(|&b| b != air) {
                    lc.sections.insert(sy, blocks);
                }
            }
            chunks.insert((wx + dx, wz + dz), lc);
        }
    }
    // `LevelHeightAccessor` for the overworld, taken from the harvest's own
    // section extent rather than assumed.
    // The geometry is a DIMENSION fact, taken from the table above, and not
    // inferred from the file. The first version of this test inferred it as
    // `min(section Y) + 1` on the assumption that a saved file carries the
    // two light-only padding sections; measured, the three harvests disagree
    // about that — the overworld's chunks carry -4..19 (no padding), the
    // nether's 0..15 (none) and the End's **-1..15** (one below, none above),
    // because vanilla writes a padding section only when the engine has data
    // in it. An inference that has to be right about three different answers
    // is not an inference, it is a guess, and its cost is silent: a
    // `min_light_section` one too high clips the bottom section out of the
    // stored set AND out of the scoring at once, and the figure comes back
    // clean over a shorter window.
    let g = geometry.get_or_insert(LightGeometry {
        min_section_y: dg.min_section_y,
        sections_count: dg.sections_count,
    });
    let geometry = *g;

    let region = Region {
        geometry,
        chunks,
        air,
    };
    // `RUSTMC_LIGHT_PER_CHUNK=1` swaps the batch driver for the per-chunk
    // one — declare, enable, propagate, drain, one chunk at a time, which is
    // the order a loading server reaches and the order
    // `SkyLightSectionStorage.createDataLayer` is sensitive to. See
    // `light_region_per_chunk`.
    let lit = if std::env::var_os("RUSTMC_LIGHT_PER_CHUNK").is_some() {
        light_region_per_chunk(&region, &props, dg.has_sky_light)
    } else {
        light_region_dimension(&region, &props, dg.has_sky_light)
    };

    // The geometry above was derived from the harvest's own section extent,
    // which is an inference. Cross-check it against the light section count
    // vanilla's own `LevelLightEngine.getLightSectionCount()` gives for this
    // dimension — `getSectionsCount() + 2` = 26 in the overworld. A harvest
    // that had lost its padding sections would otherwise shift every section
    // Y by one and the comparison would quietly read the wrong nibbles.
    // The cross-check the declared geometry earns: every section the file
    // carries must lie inside the light range it describes. A harvest from a
    // different dimension, or a table row that has drifted, shows up here
    // rather than as a clean figure over the wrong sections.
    assert!(
        min_sy >= geometry.min_light_section() && max_sy < geometry.max_light_section(),
        "{}: the harvest carries sections {min_sy}..={max_sy}, outside the light range \
         {}..{} this dimension's declared geometry {geometry:?} describes",
        d.dir,
        geometry.min_light_section(),
        geometry.max_light_section()
    );

    let mut f = Figure {
        nibbles: 0,
        differing: 0,
        scored_chunks: 0,
        per_layer: [0, 0],
        unscored_pairs: 0,
        unscored_non_uniform: 0,
        census: BTreeMap::new(),
        probe_total: 0,
        probe_matches_repeat: 0,
    };
    for dx in -r..=r {
        for dz in -r..=r {
            let key = (wx + dx, wz + dz);
            let c = &h.chunks[&key];
            f.scored_chunks += 1;
            // Every section/layer pair in the light range, not only the ones
            // the file happened to save — otherwise the blind spot is
            // measured over the artefact's own coverage and reports itself
            // small.
            let empty = rustmc_world::anvil::SectionLight::default();
            for sy in geometry.min_light_section()..geometry.max_light_section() {
                let sl = c
                    .light
                    .get(&i8::try_from(sy).expect("section y fits i8"))
                    .unwrap_or(&empty);
                for (li, layer) in [LightLayer::Sky, LightLayer::Block].into_iter().enumerate() {
                    let sky = layer == LightLayer::Sky;
                    let ours_at = |i: usize| {
                        #[allow(clippy::cast_possible_truncation)]
                        let (x, y, z) =
                            ((i & 15) as u8, ((i >> 8) & 15) as u8, ((i >> 4) & 15) as u8);
                        lit.level_at(
                            layer,
                            rustmc_server::light_incremental::as_long(
                                key.0 * 16 + i32::from(x),
                                sy * 16 + i32::from(y),
                                key.1 * 16 + i32::from(z),
                            ),
                        )
                    };
                    if (sky && sl.sky.is_none()) || (!sky && sl.block.is_none()) {
                        f.unscored_pairs += 1;
                        let first = ours_at(0);
                        if (0..4096).any(|i| ours_at(i) != first) {
                            f.unscored_non_uniform += 1;
                        }
                        continue;
                    }
                    // THE PROBE, and it is asserted rather than printed. In
                    // the padding section below the world bottom vanilla's
                    // layer is created by
                    // `SkyLightSectionStorage.createDataLayer`'s
                    // `repeatFirstLayer` branch — sixteen copies of the
                    // bottom y-slice of the nearest stored section above —
                    // and nothing in this tree reaches that branch with a
                    // section that has already been lit. This counts how
                    // many of vanilla's nibbles here are exactly that copy
                    // of OUR converged slice, which is the difference
                    // between "we compute the wrong light" and "we compute
                    // it at the wrong moment".
                    let probe = sky && sy == geometry.min_light_section();
                    for i in 0..4096usize {
                        #[allow(clippy::cast_possible_truncation)]
                        let (x, y, z) =
                            ((i & 15) as u8, ((i >> 8) & 15) as u8, ((i >> 4) & 15) as u8);
                        let v = sl.nibble(sky, x, y, z).expect("array present");
                        if probe {
                            let above = lit.level_at(
                                layer,
                                rustmc_server::light_incremental::as_long(
                                    key.0 * 16 + i32::from(x),
                                    (sy + 1) * 16,
                                    key.1 * 16 + i32::from(z),
                                ),
                            );
                            f.probe_total += 1;
                            if v == above {
                                f.probe_matches_repeat += 1;
                            }
                        }
                        let p = rustmc_server::light_incremental::as_long(
                            key.0 * 16 + i32::from(x),
                            sy * 16 + i32::from(y),
                            key.1 * 16 + i32::from(z),
                        );
                        let ours = lit.level_at(layer, p);
                        f.nibbles += 1;
                        if v != ours {
                            f.differing += 1;
                            f.per_layer[li] += 1;
                            *f.census.entry((sy, v, ours)).or_default() += 1;
                        }
                    }
                }
            }
        }
    }
    f
}

/// Add the radius the window actually used to the figure, so the report can
/// say it.
struct Reported {
    f: Figure,
    r: i32,
}

/// The commonest non-air state in this harvest, which is what a positive
/// control has to move to be a control at all.
fn commonest_solid(d: &Dimension) -> String {
    let h = load_harvest(d.dir);
    let mut counts: BTreeMap<String, usize> = BTreeMap::new();
    for c in h.chunks.values().take(16) {
        for s in &c.sections {
            for i in 0..4096usize {
                let idx = if s.blocks.is_empty() {
                    0
                } else {
                    usize::from(s.blocks[i])
                };
                let name = &s.palette[idx];
                if name != "minecraft:air" {
                    *counts.entry(name.clone()).or_default() += 1;
                }
            }
        }
    }
    counts
        .into_iter()
        .max_by_key(|(_, n)| *n)
        .map(|(k, _)| k)
        .unwrap_or_else(|| panic!("{}: the harvest holds no non-air block", d.dir))
}

fn measure(d: &Dimension, over: Option<&str>) -> Reported {
    let h = load_harvest(d.dir);
    let (r, _) = largest_window(&h, radius());
    Reported {
        f: compare(d, over),
        r,
    }
}

/// The figure, with its denominator and its command, for every dimension the
/// box holds a lit harvest of.
///
/// This is a **measurement**, not a pass/fail gate on exactness: vanilla's
/// saved light is the end of an edit history and ours is a from-scratch
/// relight of the final blocks, so a non-zero residual here is expected and
/// is the quantity of interest. What is asserted is that the comparison
/// happened at all, that the figure's blind spot stays empty, and a loose
/// ratchet that refuses a change making the engine wrong about most of a real
/// world.
///
/// **The nether and the End are here for the off-by-five.** Both have
/// `minSectionY == 0`, which `docs/AGENT-BRIEF.md` names as the case that
/// hides every confusion between a mask index and a section Y, and both have
/// `hasSkyLight() == false` — `LevelLightEngine` builds no `SkyLightEngine`
/// at all, so the packet carries no sky bit rather than an empty one. A port
/// that lit the sky anyway would put 15s on the wire for a dimension with no
/// sky, and the overworld harvest cannot see that.
#[test]
fn our_light_against_the_harvested_nibbles() {
    let mut total = 0usize;
    let mut differing = 0usize;
    for d in &DIMENSIONS {
        let Reported { f, r } = measure(d, None);
        let pct = 100.0 - 100.0 * f.differing as f64 / f.nibbles as f64;
        println!(
            "harvest light, vanilla first — {}: {} of {} nibbles differ ({pct:.6}% agree) over \
             {} chunks at radius {r}; sky {} block {}",
            d.dir, f.differing, f.nibbles, f.scored_chunks, f.per_layer[0], f.per_layer[1],
        );
        if f.probe_total > 0 {
            println!(
                "  repeatFirstLayer probe, section {}: {} of {} of vanilla's nibbles equal OUR \
                 converged value at the bottom slice of the section above",
                dimension_geometry(d).min_section_y - 1,
                f.probe_matches_repeat,
                f.probe_total,
            );
            // This is the attribution for the End's residual and it is an
            // assertion because it is the thing that could stop being true.
            // Vanilla's padding layer is `repeatFirstLayer` of a LIT section
            // — sixteen copies of the bottom y-slice — so every nibble of it
            // equals our converged value at that slice, and the residual is
            // a layer created at the wrong moment rather than a light value
            // computed wrongly. If this ever comes back short, the residual
            // has a second cause and `light_incremental::light_region_per_chunk`'s
            // note is stale.
            assert_eq!(
                f.probe_matches_repeat, f.probe_total,
                "{}: vanilla's padding section is no longer a copy of our converged \
                 bottom slice above it — the End residual's attribution has changed",
                d.dir
            );
        }
        println!(
            "  blind spot: {} of {} section/layer pairs carry no saved array (a homogeneous \
             layer is not written); ours is non-uniform in {} of them",
            f.unscored_pairs,
            f.unscored_pairs + f.nibbles / 4096,
            f.unscored_non_uniform
        );
        if f.differing > 0 {
            let mut rows: Vec<_> = f.census.iter().collect();
            rows.sort_by_key(|(_, n)| std::cmp::Reverse(**n));
            for ((sy, van, ours), n) in rows.into_iter().take(12) {
                println!("    section {sy}: vanilla {van} ours {ours} — {n} nibbles");
            }
        }
        assert!(
            f.nibbles > 20_000,
            "{}: only {} nibbles compared — the window scored almost nothing and the figure \
             means nothing",
            d.dir,
            f.nibbles
        );
        // The blind spot must stay a blind spot and not become a hiding
        // place. A saved array is absent exactly when vanilla's layer was
        // homogeneous, so ours being non-uniform in one of those pairs is a
        // real divergence the nibble count cannot see.
        assert_eq!(
            f.unscored_non_uniform, 0,
            "{}: our layer is non-uniform in {} of the {} section/layer pairs vanilla saved no \
             array for — the residual can hide there and this figure cannot see it",
            d.dir, f.unscored_non_uniform, f.unscored_pairs
        );
        let ratio = f.differing as f64 / f.nibbles as f64;
        assert!(
            ratio < 0.02,
            "{}: {} of {} nibbles differ ({:.4}%), over the 2% ceiling",
            d.dir,
            f.differing,
            f.nibbles,
            ratio * 100.0
        );
        total += f.nibbles;
        differing += f.differing;
    }
    println!(
        "  ALL DIMENSIONS: {differing} of {total} nibbles differ\n  \
         RUSTMC_LIGHT_HARVEST_RADIUS={} cargo test --release -p rustmc-server --test \
         light_harvest -- --nocapture",
        radius()
    );
    assert!(
        total > 1_000_000,
        "only {total} nibbles over all dimensions"
    );
}

/// The positive control. Move one block's light emission and the figure must
/// move — otherwise the comparison above is reading something other than our
/// engine's output.
#[test]
fn moving_one_emission_moves_the_figure() {
    let (_, ids) = load_props();
    // Stone: 0 emission in vanilla, and the commonest block in a generated
    // world, so making it a light source cannot fail to change the answer if
    // the answer is really ours.
    let _ = ids;
    for d in &DIMENSIONS {
        // The commonest solid state in this dimension's own window, so the
        // control cannot be a no-op the way `minecraft:stone` is in the
        // nether — which it was, and which made that dimension's control
        // report 0 against 0 until this was measured rather than assumed.
        let name = commonest_solid(d);
        let base = compare(d, None);
        let moved = compare(d, Some(&name));
        println!(
            "positive control {}: {name} as emitter — baseline {} differing, moved {} differing",
            d.dir, base.differing, moved.differing
        );
        assert_eq!(
            base.nibbles, moved.nibbles,
            "{}: the control changed the denominator, so the two figures are not comparable",
            d.dir
        );
        assert_ne!(
            base.differing, moved.differing,
            "{}: making {name} emit light left the harvest comparison unchanged — it is not \
             reading our engine's output",
            d.dir
        );
    }
}
