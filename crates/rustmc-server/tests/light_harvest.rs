//! Our light engine against **vanilla's own saved nibbles**, on real
//! generated terrain. Vanilla first.
//!
//! # Why this is a different instrument from the goldens
//!
//! `tests/light_incremental_golden.rs` and `tests/light_incremental_mutation.rs`
//! grade the engine against nine-chunk worlds that a Java dumper built for the
//! purpose. Every block in them was chosen. This one grades it against
//! `oracle-work/vanilla-r7`, which is a real vanilla server's saved region
//! files: 362 chunks at `minecraft:full`, every one with `isLightOn: 1` and
//! both nibble arrays on disk, over terrain nobody designed.
//!
//! The three ways it is stronger, and the one way it is weaker:
//!
//! * **The blocks are vanilla's.** Both sides read the same palette out of
//!   the same file, so a worldgen residual cannot leak into this number. What
//!   is compared is the light engine and nothing else.
//! * **The scale is four orders of magnitude larger** than the goldens' hand
//!   built rooms, and the terrain has overhangs, caves, water and leaves that
//!   nobody thought to put in a test world.
//! * **It reads a shipped artefact.** The goldens are regenerated by a dumper
//!   this repo wrote; these files were written by the server itself.
//! * Weaker in one respect, and it is why the goldens stay: vanilla's saved
//!   light is the end of an *edit history* — generation, then decoration,
//!   then feature placement, each calling `checkBlock` — and we light the
//!   final blocks from scratch. Where those differ, the difference is the
//!   `relit` class and is not a defect. The figure is reported with that
//!   stated rather than assumed away.
//!
//! # Only interior chunks are scored
//!
//! `LightEngine.getState` returns **bedrock** for a position in an unloaded
//! chunk, so a chunk at the edge of the loaded window is lit against a wall
//! that vanilla did not have. Only chunks all eight of whose neighbours are
//! loaded are counted, and the count of those is printed beside the figure —
//! a window that scored nothing would say so.

