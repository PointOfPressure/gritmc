#!/usr/bin/env python3
"""Prove rule 18 can go red IN A GATE DIRECTORY — the tree that has no `.git`.

    python3 ci/figure-provenance-falsify.py    # ~1 s, no build, no jar, no box

# WHY THIS FILE EXISTS AND WHY `ci/check-figures-falsify.py` IS NOT ENOUGH

Rule 18 says a `provenance` must name a commit that git resolves. Until
2026-09-05 it ran in exactly two places and could ask in neither of the ones
that count:

* `ci/t0-remote.sh` rsyncs the tree with `--exclude .git`, so in every gate
  directory on the box `git rev-parse --git-dir` fails and the rule degraded to
  its shape half — "is there a hex-shaped run that is not a date". `48d1efb`
  passes that and names no object anywhere.
* `ci/figure-provenance.py --check` prints `SKIPPED` there and exits 0.

Measured on main `1a31e0a56`, one tree read two ways:

    worktree with history   ci/check-figures.py   exit 1, 3 PROVENANCE-NO-COMMIT
    rsync of it, no .git    ci/check-figures.py   exit 0, FIGURES GREEN

and the three reds were real: `48d1efb` (`bench-r32-rustmc-cpu`), `00ab0bde`
(`t0-floor-targets`) and `917ebc43` (`handoff-terminals-unforced`) resolve to no
object in any repository, reflog or branch on this box.

**`ci/check-figures-falsify.py` had three rule-18 cases and none of them could
have caught this**, because its fixture calls `git init`: all three exercise the
resolving arm, which is the arm no gate ever takes. A falsifier running in a
different mode from the gate proves a rule can go red somewhere nobody runs it,
which is the same defect one level up. So every case below runs in a fixture
with **no repository**, which is the gate's own mode, and the green control is
as load-bearing as the reds: a rule that reds on everything would satisfy the
red cases and be worthless.

The fixture, the ledger and the documents are `ci/check-figures-falsify.py`'s,
imported rather than copied — two fixtures for one checker is two answers
waiting for an occasion, and the fixture is the part that goes stale.

Exit 0 all cases behaved, 1 a case did not, 2 the harness could not run.
"""

from __future__ import annotations

import hashlib
import importlib.util
import shutil
import subprocess
import sys
import tempfile
from copy import deepcopy
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHECKER = ROOT / "ci" / "check-figures.py"
STAMPER = ROOT / "ci" / "figure-provenance.py"
SIBLING = ROOT / "ci" / "check-figures-falsify.py"


def load_sibling():
    spec = importlib.util.spec_from_file_location("cff", SIBLING)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def digest(prov: str) -> str:
    return hashlib.sha256(prov.encode("utf-8")).hexdigest()[:16]


def snapshot(rows: list[tuple[str, str, str]], version: str = "1") -> str:
    body = [
        "# GENERATED by ci/figure-provenance.py --snapshot.",
        f"version {version}",
        "tree " + "0" * 40,
        f"figures {len(rows)}",
        *[f"{a}\t{b}\t{c}" for a, b, c in rows],
    ]
    return "\n".join(body) + "\n"


def main() -> int:
    if not CHECKER.exists() or not STAMPER.exists() or not SIBLING.exists():
        print("figure-provenance-falsify: a checker is missing", file=sys.stderr)
        return 2
    cff = load_sibling()

    # The gate's provenance is a real-looking sha that resolves NOWHERE, which
    # is the shape of all three figures this repair was written for. In a
    # fixture with no repository it cannot be resolved by anybody; what the
    # snapshot says about it is the entire question.
    ORPHAN = "48d1efb"
    base = deepcopy(cff.BASE)
    for f in base:
        f["provenance"] = ORPHAN
    ids = [f["id"] for f in base]
    good = [(i, digest(ORPHAN), "a" * 40) for i in ids]

    work = Path(tempfile.mkdtemp(prefix="figprov-falsify."))
    failures: list[str] = []
    try:
        (work / "ci" / "checks").mkdir(parents=True)
        (work / "docs").mkdir()
        shutil.copy(CHECKER, work / "ci" / "check-figures.py")
        # Both scripts import `ci/lib/box_env.py` to find an object store (the
        # `.gitstore` `ci/t0-remote.sh` ships). Without it in the fixture every
        # case died on the import with exit 1 and no rule evaluated, so the
        # suite read 0/8 for a reason unrelated to rule 18 — landing, 2026-09-23.
        (work / "ci" / "lib").mkdir()
        shutil.copy(ROOT / "ci" / "lib" / "box_env.py", work / "ci" / "lib" / "box_env.py")
        (work / "ci" / "fixture-artefact.sh").write_text(cff.ARTEFACT, encoding="utf-8")
        # NOT a repository, and asserted rather than assumed: the whole suite is
        # about the arm taken when there is none, and a stray `.git` above a
        # temp directory would silently run every case in the other mode.
        if subprocess.run(
            ["git", "-C", str(work), "rev-parse", "--git-dir"], capture_output=True
        ).returncode == 0:
            print(
                "figure-provenance-falsify: the fixture resolved a git dir, so every "
                "case below would exercise the arm the gate never takes",
                file=sys.stderr,
            )
            return 2

        def case(name: str, want_rule: str | None, figures, meta, snap: str | None):
            stamp = work / ".figure-provenance"
            if snap is None:
                stamp.unlink(missing_ok=True)
            else:
                stamp.write_text(snap, encoding="utf-8")
            code, out = cff.run(work, figures, meta)
            got = sorted({
                l.split("]")[0].split("[")[1]
                for l in out.splitlines()
                if l.startswith("FIGURES RED [")
            })
            if want_rule is None:
                ok = code == 0 and not got
                verdict = "green" if ok else f"exit {code}, rules {got}"
            else:
                ok = code == 1 and got == [want_rule]
                verdict = f"exit {code}, rules {got or 'none'}"
            print(f"  {'ok  ' if ok else 'FAIL'}  {name:<44} {verdict}")
            if not ok:
                failures.append(name)

        # -- the control. Everything below is a mutation of exactly this ------
        case("green: stamp matches the ledger", None, base, cff.META, snapshot(good))

        # -- the transport itself ---------------------------------------------
        case("no stamp shipped", "PROVENANCE-NO-SNAPSHOT", base, cff.META, None)
        case(
            "stamp written by a future version",
            "PROVENANCE-NO-SNAPSHOT",
            base,
            cff.META,
            snapshot(good, version="2"),
        )
        truncated = snapshot(good).replace(f"figures {len(good)}", f"figures {len(good) + 1}")
        case("stamp declares a count it does not carry", "PROVENANCE-NO-SNAPSHOT",
             base, cff.META, truncated)

        # -- the rule the transport was hiding ---------------------------------
        # THE CASE THIS WHOLE FILE EXISTS FOR. `48d1efb` is hex, is not a date,
        # and names no commit. The old shape fallback passed it; the stamp says
        # what the repository said, and the rule reds in the gate.
        case(
            "a provenance that resolves nowhere",
            "PROVENANCE-NO-COMMIT",
            base,
            cff.META,
            snapshot([(i, digest(ORPHAN), "UNRESOLVED") for i in ids]),
        )

        # -- the stamp cannot be about a different string -----------------------
        edited = deepcopy(base)
        edited[0]["provenance"] = ORPHAN + " (re-typed after the stamp)"
        case("ledger edited after the stamp", "PROVENANCE-SNAPSHOT-STALE",
             edited, cff.META, snapshot(good))
        case("figure absent from the stamp", "PROVENANCE-SNAPSHOT-STALE",
             base, cff.META, snapshot(good[1:]))

        # -- the stamper refuses where it cannot compute an answer --------------
        shutil.copy(STAMPER, work / "ci" / "figure-provenance.py")
        (work / "ci" / "figures.toml").write_text(
            cff.ledger(base, cff.META), encoding="utf-8"
        )
        (work / ".figure-provenance").unlink(missing_ok=True)
        proc = subprocess.run(
            [sys.executable, str(work / "ci" / "figure-provenance.py"), "--snapshot"],
            capture_output=True, text=True,
        )
        wrote = (work / ".figure-provenance").exists()
        ok = proc.returncode == 2 and not wrote
        print(f"  {'ok  ' if ok else 'FAIL'}  {'--snapshot in a tree with no .git':<44} "
              f"exit {proc.returncode}, wrote={wrote}")
        if not ok:
            failures.append("--snapshot in a tree with no .git")
    finally:
        shutil.rmtree(work, ignore_errors=True)

    total = 8
    print(f"\nfigure-provenance-falsify: {total - len(failures)} passed, {len(failures)} failed")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
