#!/usr/bin/env python3
"""probe-reads.py — which rows of a use table are a reading of the probe?

`data/vanilla/use_without_item.json` is generated by driving one player at one
block state and writing down what happened (`tools/goldengen/vanilla/UseGolden.java`).
That player has a facing, a position, a game mode, an ability set and an
inventory, and a `useWithoutItem` implementation is free to read any of them.
Where it does, the recorded row is a fact about **that player**, and the table
states it as a fact about the block.

This is the static half of the audit: from the pinned jar alone, which rows sit
on a `useWithoutItem` whose bytecode reads the player argument at all. The
empirical half — which of those rows actually *move* when the player changes —
is `PROBE STANCES` in `UseGolden.java` and the `probeDependent` column it
writes. Neither subsumes the other:

* a row this script calls clean cannot move, whatever stance you try;
* a row it calls reading may still be constant, because the value read is
  discarded or steers nothing the table records — `Player.awardStat` is not a
  read at all and `Player.openMenu`'s `OptionalInt` is dropped on the floor by
  every caller in the jar.

So this bounds the defect from above and the stance sweep measures it from
below, and the two numbers are reported side by side rather than one of them
being called the answer.

    ./ci/probe-reads.py                 # the audit, as a table
    ./ci/probe-reads.py --json out.json # machine-readable
    ./ci/probe-reads.py --table data/vanilla/use_item_on.json

# Two tables, one walk

`use_item_on.json` is the same question about `BlockState.useItemOn` — offset
145 of `ServerPlayerGameMode.useItemOn` rather than offset 196 — and it is
audited by the same code. The method name and descriptor are the only things
that change, and they are read off the table's own `what` field rather than
passed in, so an audit cannot be pointed at the wrong half of the use path.

**The two are not equally exposed and the numbers should not be averaged.**
`useWithoutItem` is handed the level, the player and the hit. `useItemOn` is
handed the held stack as well and dispatches on it, and it runs *first*, so
every stance that can steer it steers what the other one is even asked. The
walk below bounds both from above in the same way and says so per table.

# What "reads the player" means here

A **read** is an invoke whose static receiver type is in the `Entity` hierarchy
and whose descriptor returns something other than `void`. A value comes back
into the block's own frame, so it can steer a branch, an argument or the return.
A `void` call is an effect *on* the player — `awardStat`, `sendOverlayMessage`,
`displayClientMessage` — and cannot change what the table records about the
block.

# Three things this deliberately does not do, each stated because it bounds a number

* **`invokespecial` and `invokestatic` are resolved exactly.**
  `ci/jarcallgraph.py` devirtualises every invoke to all subtypes declaring the
  signature, which is right for its own purpose and wrong here:
  `DaylightDetectorBlock.useWithoutItem` ends its early-out with
  `invokespecial BaseEntityBlock.useWithoutItem`, and devirtualised that one
  super-call fans out to every `useWithoutItem` in the jar. The first run of
  this audit reported **179 of 184** rows probe-reading on the strength of it.
  Opcode-aware, the same walk reports a much smaller number, and the difference
  is entirely that one edge class.
* **The walk stays inside the block packages.** Leaving them produced the other
  half of that 179: `Level.playSound(@Nullable Player, ...)` carries the
  clicking player only as the client to *exclude* from the broadcast, and
  `PlayerList.broadcast` then reads `getX/getY/getZ` off every **other** player.
  That is a read of the audience, not of the probe, and the table records no
  audience. Every button, door, trapdoor and lever entered the count that way.
* **The player is assumed to travel only as a parameter.** A `useWithoutItem`
  that stashed the player in a field and read it back through a static would be
  reported clean. Nothing in the 184 does, checked by eye over the call sites
  this prints, but the assumption is the reason the clean set is a *claim* and
  not a proof.
"""

import argparse
import collections
import hashlib
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from jarcallgraph import ILEN, INVOKES, JarGraph  # noqa: E402

# name -> descriptor, keyed by the string a table's `what` field opens with.
# Read off the table rather than passed in: an audit pointed at the wrong half
# of the use path would resolve nothing, report every row unresolved, and the
# refusal at the bottom would never fire because there would be no rows left to
# contradict.
METHODS = {
    "useWithoutItem": (
        "(Lnet/minecraft/world/level/block/state/BlockState;"
        "Lnet/minecraft/world/level/Level;"
        "Lnet/minecraft/core/BlockPos;"
        "Lnet/minecraft/world/entity/player/Player;"
        "Lnet/minecraft/world/phys/BlockHitResult;)"
        "Lnet/minecraft/world/InteractionResult;"
    ),
    "useItemOn": (
        "(Lnet/minecraft/world/item/ItemStack;"
        "Lnet/minecraft/world/level/block/state/BlockState;"
        "Lnet/minecraft/world/level/Level;"
        "Lnet/minecraft/core/BlockPos;"
        "Lnet/minecraft/world/entity/player/Player;"
        "Lnet/minecraft/world/InteractionHand;"
        "Lnet/minecraft/world/phys/BlockHitResult;)"
        "Lnet/minecraft/world/InteractionResult;"
    ),
}
# The dumper whose probe produced each table, for the stamp. `UseGolden.java`
# is in both because both harnesses are it: the level, the player, the stance
# list and the component/tag binding all live there.
DUMPERS = {
    "useWithoutItem": ["tools/goldengen/vanilla/UseGolden.java"],
    "useItemOn": [
        "tools/goldengen/vanilla/UseGolden.java",
        "tools/goldengen/vanilla/UseItemOnGolden.java",
    ],
}
# Where a use rule's own logic lives. `block/` covers the blocks and their
# block entities; `state/` is where `BlockState.useWithoutItem` forwards from.
#
# **`world/item/` and `core/cauldron/` were added 2026-08-12, and the
# containment refusal at the bottom of this file is what added them.** With the
# fence at the block packages alone, this walk called seven rows of
# `use_item_on.json` clean that the stance sweep measures moving — cake, the
# four cauldrons, the composter and the flower pot — and every one of them
# reads the probe through `ItemStack.consume(n, player)`, which is
# `if (entity == null || !entity.hasInfiniteMaterials()) shrink(n)`, or through
# `ItemUtils.createFilledResult(stack, player, ...)`, which is the same read
# one call further out. `useItemOn` is *handed the stack*, so item code is
# where half of its player reads live and fencing them out was fencing out the
# half this table is about.
#
# The two packages that must stay out stay out: the 2026-08-11 measurement that
# put this fence here was about `Level.playSound` -> `PlayerList.broadcast`
# reading `getX/getY/getZ` off every OTHER player, and `Level` and `PlayerList`
# are in neither of the packages added here. The count is re-measured below
# rather than assumed unchanged.
BLOCK_PKGS = (
    "net/minecraft/world/level/block/",
    "net/minecraft/world/level/blockentity/",
    "net/minecraft/world/item/",
    "net/minecraft/core/cauldron/",
)
ENTITY_ROOTS = (
    "net/minecraft/world/entity/Entity",
    "net/minecraft/world/entity/LivingEntity",
    "net/minecraft/world/entity/player/Player",
)
ENTITY_PARAM_TYPES = (
    "Lnet/minecraft/world/entity/Entity;",
    "Lnet/minecraft/world/entity/LivingEntity;",
    "Lnet/minecraft/world/entity/player/Player;",
    "Lnet/minecraft/server/level/ServerPlayer;",
)
INVOKESPECIAL, INVOKESTATIC = 0xB7, 0xB8


class OpcodeGraph(JarGraph):
    """`JarGraph` plus the opcode each call site used.

    `_code` is overridden rather than the module edited: `ci/jarcallgraph.py` is
    the census's substrate and its devirtualise-everything resolution is correct
    there. This subclass wants the *opposite* default for two of the five invoke
    opcodes and nothing else, so it re-walks the same code array for the invokes
    alone and records `(offset -> opcode)` beside them.
    """

    def __init__(self, jar_path):
        self.opcode_at = {}
        super().__init__(jar_path)

    def _code(self, me, name, desc, code, ent, ref, cls, utf, bsm):
        super()._code(me, name, desc, code, ent, ref, cls, utf, bsm)
        key = (me, name, desc)
        i, n = 0, len(code)
        while i < n:
            op = code[i]
            ln = ILEN[op]
            if op == 0xC4:
                ln = 6 if code[i + 1] == 0x84 else 4
            elif op in (0xAA, 0xAB):
                p = i + 1
                p += (4 - (p % 4)) % 4
                if op == 0xAA:
                    lo, hi = struct.unpack_from(">ii", code, p + 4)
                    ln = (p + 12 + 4 * (hi - lo + 1)) - i
                else:
                    (np_,) = struct.unpack_from(">i", code, p + 4)
                    ln = (p + 8 + 8 * np_) - i
            if op in INVOKES and op != 0xBA:
                t = ref(struct.unpack_from(">H", code, i + 1)[0])
                if t:
                    self.opcode_at.setdefault(key, {})[t] = op
            i += ln if ln > 0 else 1


def ret_of(desc):
    return desc.split(")")[1]


def takes_entity(desc):
    args = desc.split(")")[0]
    return any(t in args for t in ENTITY_PARAM_TYPES)


def short(m):
    return "%s.%s" % (m[0].rsplit("/", 1)[-1], m[1])


def digest(path, n=12):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()[:n]


class Audit:
    def __init__(self, jar, table, method=None):
        self.g = OpcodeGraph(jar)
        self.doc = json.load(open(table))
        what = self.doc.get("what", "")
        if method is None:
            method = next(
                (m for m in METHODS if what.startswith("BlockState.%s" % m)), None
            )
        if method not in METHODS:
            sys.exit(
                "cannot tell which method %s describes (its `what` is %r); pass --method"
                % (table, what)
            )
        self.method = method
        self.desc = METHODS[method]
        self._shapes = None
        sub = self.g.subtypes()
        ent = set()
        for r in ENTITY_ROOTS:
            ent |= set(sub.get(r, ())) | {r}
        self.entity = ent
        # direct reads: an entity call that hands a value back
        self.reads = {}
        for m, ts in self.g.calls.items():
            hit = {
                t
                for t in ts
                if t[0] in ent and t[1] != "<init>" and ret_of(t[2]) != "V"
            }
            if hit:
                self.reads[m] = hit
        self.edge = self._edges()

    def _bodyless(self, m):
        """True when `m` has no code — abstract, or an interface method."""
        return not self.g.calls.get(m) and not self.g.events.get(m)

    def _same_shape(self, desc):
        """Every method in the walked packages with this exact descriptor.

        **The functional-interface hole, closed 2026-08-12.**
        `AbstractCauldronBlock.useItemOn` is two calls: `Dispatcher.get(stack)`
        and `CauldronInteraction.interact(...)`. `CauldronInteraction` is a
        functional interface, so `interact` resolves to itself, has no body,
        and the walk stopped there — with the entire cauldron behaviour, and
        the `Player.hasInfiniteMaterials` read inside it, on the far side. Four
        rows of `use_item_on.json` move under the stance sweep that the walk
        called clean, and the containment refusal at the bottom of this file is
        what said so.

        A lambda body is not reachable from its call site in bytecode — only
        from the `invokedynamic` that creates it, which is in whichever
        `<clinit>` built the dispatch table. So the edge has to be recovered by
        signature, and **the descriptor is what makes that narrow rather than
        wild**: this one is
        `(BlockState, Level, BlockPos, Player, InteractionHand, ItemStack) ->
        InteractionResult` and matches 21 methods in the whole jar.

        This over-approximates, in the direction the rest of the file already
        over-approximates: it can only add reads, and a row this walk calls
        clean is the claim being protected.
        """
        if self._shapes is None:
            self._shapes = collections.defaultdict(set)
            for c, ms in self.g.declares.items():
                if not c.startswith(BLOCK_PKGS):
                    continue
                for name, d in ms:
                    self._shapes[d].add((c, name, d))
        return self._shapes.get(desc, set())

    def _edges(self):
        """Block-package call edges that can carry the player, opcode-aware."""
        out = collections.defaultdict(set)
        for m, ts in self.g.calls.items():
            if not m[0].startswith(BLOCK_PKGS):
                continue
            ops = self.g.opcode_at.get(m, {})
            for t in ts:
                if not (t[0] in self.entity or takes_entity(t[2])):
                    continue
                op = ops.get(t)
                if op in (INVOKESPECIAL, INVOKESTATIC):
                    d = self.g._declaring(t[0], t[1], t[2])
                    targets = {(d, t[1], t[2])} if d else set()
                else:
                    targets = set(self.g.resolve(t))
                    if all(self._bodyless(n) for n in targets):
                        targets |= self._same_shape(t[2])
                for n in targets:
                    if n[0].startswith(BLOCK_PKGS):
                        out[m].add(n)
        return out

    def walk(self, root, maxd=8):
        """Every (path, reads) the player can be carried to from `root`."""
        seen, frontier, found, d = {root}, [(root, [root])], [], 0
        while frontier and d < maxd:
            nxt = []
            for m, path in frontier:
                if m in self.reads:
                    found.append((path, sorted(self.reads[m])))
                for n in self.edge.get(m, ()):
                    if n not in seen:
                        seen.add(n)
                        nxt.append((n, path + [n]))
            frontier, d = nxt, d + 1
        return found

    def run(self):
        simple = collections.defaultdict(list)
        for c in self.g.classes:
            if "$" not in c:
                simple[c.rsplit("/", 1)[-1]].append(c)
        rows, unresolved = {}, []
        for r in self.doc["table"]:
            cands = simple.get(r["class"], [])
            if len(cands) != 1:
                unresolved.append((r["block"], r["class"], cands))
                continue
            d = self.g._declaring(cands[0], self.method, self.desc)
            if d is None:
                unresolved.append((r["block"], r["class"], "no " + self.method))
                continue
            rows[r["block"]] = {
                "class": r["class"],
                "declaredBy": d.rsplit("/", 1)[-1],
                "reads": self.walk((d, self.method, self.desc)),
                "probeDependent": r.get("probeDependent"),
            }
        return rows, unresolved


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument("--jar", default=None)
    ap.add_argument("--table", default=os.path.join(root, "data/vanilla/use_without_item.json"))
    ap.add_argument("--method", default=None, choices=sorted(METHODS))
    ap.add_argument("--json", default=None)
    a = ap.parse_args()
    if a.jar is None:
        ver = "26.2"
        for line in open(os.path.join(root, "crates/rustmc-proto/src/lib.rs")):
            if "GAME_VERSION: &str" in line:
                ver = line.split('"')[1]
                break
        a.jar = os.path.join(
            root, "oracle-work/vanilla-%s/versions/%s/server-%s.jar" % (ver, ver, ver)
        )
    if not os.path.exists(a.jar):
        sys.exit("no jar at %s" % a.jar)

    audit = Audit(a.jar, a.table, a.method)
    rows, unresolved = audit.run()
    reading = {b: v for b, v in rows.items() if v["reads"]}
    doc = audit.doc
    moved = {b for b, v in rows.items() if v["probeDependent"]}
    unknown = {
        r["block"]
        for r in doc["table"]
        if r.get("probeUnknown") and r["block"] in rows
    }

    byclass = collections.defaultdict(list)
    for b, v in rows.items():
        byclass[v["class"]].append(b)
    reading_classes = sorted({v["class"] for v in reading.values()})

    print("probe-reads: %s  (BlockState.%s)" % (a.table, audit.method))
    print(
        "  %d of %d rows sit on a %s that reads the player "
        "(%d of %d block classes)"
        % (len(reading), len(rows), audit.method, len(reading_classes), len(byclass))
    )
    if unresolved:
        print("  !! %d rows unresolved against the jar" % len(unresolved))
        for u in unresolved:
            print("     %s %s %s" % u)
    print()
    for c in reading_classes:
        bs = sorted(b for b in byclass[c] if b in reading)
        v = reading[bs[0]]
        calls = collections.OrderedDict()
        for path, rs in v["reads"]:
            via = " -> ".join(short(m) for m in path[1:]) or "(self)"
            for t in rs:
                calls.setdefault("%s.%s%s" % (t[0].rsplit("/", 1)[-1], t[1], t[2]), via)
        print("  %-28s rows=%-3d via %s" % (c, len(bs), v["declaredBy"]))
        for sig, via in calls.items():
            print("      %-58s  %s" % (sig.split("(")[0], via))
    clean = sorted({v["class"] for b, v in rows.items() if not v["reads"]})
    print("\n  no player read at all (%d classes): %s" % (len(clean), ", ".join(clean)))

    # ---- the split, from the dumper's own stance sweep ---------------------
    #
    # `probeDependent` is measured, not inferred: `UseGolden` re-probes every
    # state under every stance in `STANCES` and sets the column when the
    # recorded row moved. So this half needs no approximation and the two halves
    # are allowed to disagree only in one direction — anything that MOVED must
    # also READ, and a moved row this script called clean would mean the walk
    # above has a hole.
    print()
    containment_broken = sorted(moved - set(reading))
    constant = set(reading) - moved

    def cells_of(row):
        """Every recorded cell of a row, whatever the table's shape.

        `use_without_item.json` lists one cell per state.
        `use_item_on.json` lists one `default` cell per state plus the
        exceptions, because its second axis is 1,537 items wide and writing
        them out would be a hundred-megabyte file saying the same thing 1,500
        times. The decomposition below asks the same question of both — how
        much of "constant across every stance" is constant only because it was
        never measured — so it has to see through that compression rather than
        report the compressed table as having no refusals at all.
        """
        for st in row.get("states", []):
            if "default" in st:
                yield st["default"]
                for group in st.get("except", []):
                    yield group["cell"]
            else:
                yield st

    refusal_share = {}
    for r in doc["table"]:
        cs = list(cells_of(r))
        if cs:
            refusal_share[r["block"]] = (
                sum(1 for c in cs if "refused" in c), len(cs)
            )
    all_refused = {b for b in constant
                   if refusal_share.get(b, (0, 0))[0] == refusal_share.get(b, (0, 0))[1] > 0}
    some_refused = {b for b in constant
                    if b not in all_refused and refusal_share.get(b, (0, 0))[0] > 0}
    print("  SPLIT (denominator: %d rows in the table)" % len(rows))
    print("    reads the probe                     %4d" % len(reading))
    print("      of which the row MOVES            %4d   %s"
          % (len(moved), ", ".join(sorted({rows[b]["class"] for b in moved}))))
    print("      of which constant across stances  %4d" % len(constant))
    print("        - every cell a refusal          %4d   (constant because unmeasured)"
          % len(all_refused))
    print("        - some cells refusals           %4d" % len(some_refused))
    print("        - fully measured and constant   %4d"
          % (len(constant) - len(all_refused) - len(some_refused)))
    print("    never reads the probe               %4d" % (len(rows) - len(reading)))
    print("    a stance refused where base did not %4d" % len(unknown))
    print("\n  THE %d, BY NAME — every row whose recorded answer is a reading of one"
          % len(moved))
    print("  player. These are not rows to bulk-convert on suspicion; they are the")
    print("  list whoever ports them works from.")
    axes_of = {r["block"]: r.get("probeAxes", []) for r in doc["table"]}
    for b in sorted(moved):
        print("    %-34s %-24s %s"
              % (b, rows[b]["class"], ", ".join(axes_of.get(b, []))))
    print()
    print("    stances swept: %d of %d  (unavailable: %s)"
          % (len(doc.get("probeStances", [])) + 1 - len(doc.get("probeStancesUnavailable", {})),
             len(doc.get("probeStances", [])) + 1,
             ", ".join(sorted(doc.get("probeStancesUnavailable", {}))) or "none"))

    # ---- the stamp --------------------------------------------------------
    #
    # Four inputs, not one. A single-input claim has been inherited across a
    # re-measure on this project once already: the jar alone does not move when
    # the dumper changes, and the table alone does not move when this script's
    # resolution changes, so either on its own can carry a stale number forward
    # looking fresh.
    here = os.path.abspath(__file__)
    print(
        "\nSTAMP        jar=%s table=%s dumper=%s audit=%s rows=%d reads=%d moves=%d"
        % (
            digest(a.jar),
            digest(a.table),
            "+".join(digest(os.path.join(root, d)) for d in DUMPERS[audit.method]),
            digest(here),
            len(rows),
            len(reading),
            len(moved),
        )
    )

    if a.json:
        with open(a.json, "w") as f:
            json.dump(
                {
                    "rows": len(rows),
                    "reading": len(reading),
                    "byBlock": {
                        b: {
                            "class": v["class"],
                            "declaredBy": v["declaredBy"],
                            "calls": sorted(
                                {
                                    "%s.%s" % (t[0].rsplit("/", 1)[-1], t[1])
                                    for _p, rs in v["reads"]
                                    for t in rs
                                }
                            ),
                        }
                        for b, v in sorted(rows.items())
                        if v["reads"]
                    },
                },
                f,
                indent=1,
                sort_keys=True,
            )
        print("  json -> %s" % a.json)

    # **Non-zero, not a warning.** The containment is the only thing the two
    # instruments can check about each other, and a script that printed `!!` and
    # exited 0 would be the third gate on this project that could not fail. A
    # row that MOVED under a real sweep and that this walk calls clean means the
    # walk has a hole; the sweep is the measurement and this is the estimate, so
    # the estimate is what is wrong.
    if containment_broken:
        print(
            "\nprobe-reads: REFUSED — %d row(s) move under the stance sweep that "
            "this walk calls clean:\n  %s\nThe static walk has a hole. Trust the "
            "sweep; the 'never reads the probe' set above is not safe to act on."
            % (len(containment_broken), "\n  ".join(containment_broken)),
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
