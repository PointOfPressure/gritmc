#!/usr/bin/env bash
# t2-vanilla-loads-ours.sh — hand a region file OUR writer produced to a REAL
# vanilla server and make vanilla say what is in it.
#
# WHY THIS EXISTS
#
# `crates/rustmc-world/src/anvil.rs` has had a chunk writer for a long time,
# and everything that ever checked it was our own reader:
# `a_chunk_survives_a_write_read_round_trip`, and
# `real_vanilla_chunks_survive_a_rewrite` — which takes a region vanilla wrote,
# rewrites it, and reads it back **with us**. That test's own doc comment says
# a round trip through our reader "is weaker than it sounds ... a lenient
# reader could accept bytes vanilla would not", and then does not close the
# gap it names. A reader and a writer authored together can agree on the same
# wrong thing indefinitely.
#
# So: only vanilla can settle whether vanilla can load what we wrote. This
# writes into a world, boots vanilla on it, and greps vanilla's own console
# output for the answer.
#
# THE THREE ARMS, AND WHAT EACH ONE CATCHES
#
# One assertion would not have been enough, and the reason is the shape this
# project keeps rediscovering: **a chunk that vanilla cannot read is a chunk
# vanilla silently regenerates.** The world here was generated by vanilla from
# a known seed, so a regenerated chunk is *identical to the original terrain*.
# Any arm that only asserts "the natural terrain is there" therefore passes
# just as happily when our file was rejected outright. That arm cannot fail.
#
#   A  the sentinel in the FIRST-poked chunk
#      Fails if vanilla could not read our bytes (regenerates -> air), and
#      fails if the second poke destroyed the first chunk.
#
#      **MEASURED, and the prediction was wrong about which check fires.**
#      This was written as "the arm that catches a truncating writer", on the
#      reasoning that `write_region` lays out only the chunks it is handed and
#      drops the region's other 1,023 slots, so under it the second poke
#      deletes the first sentinel. Substituting `write_region` for
#      `write_region_merging` in `anvil-probe` and running the gate:
#
#          poked (1032, 200, 1032) = minecraft:diamond_block in chunk (64, 64)
#          anvil-probe: chunk (65, 65) is not present in .../r.2.2.mca
#          T2-VANILLA-LOADS-OURS RED — second poke failed
#
#      It never reaches arm A, or the chunk-count assertion, or vanilla. The
#      *first* poke already emptied the region, so the second one cannot find
#      the chunk it was asked to write to. The gate is right and red for the
#      right reason; the reason is one stage earlier than this comment said.
#
#      Arm A therefore stands as the backstop for the subtler case — a merge
#      that drops *some* chunks, or a file vanilla rejects — rather than as
#      the sole detector of wholesale truncation.
#
#      IF YOU REPEAT THAT FALSIFICATION, TOUCH THE SOURCE AFTERWARDS. Undoing
#      it by restoring a backup or re-rsyncing from the laptop puts an *older*
#      mtime on the file than the falsified build already has, `cargo` decides
#      the binary is fresh, and the next run silently reuses the truncating
#      probe — which looks exactly like the gate having become permanently
#      red. `cargo build` at the top of this script cannot help: it is doing
#      what it was asked to.
#
#   B  the sentinel in the SECOND-poked chunk
#      Fails if vanilla could not read our bytes at all. B alone is the
#      degenerate version of this test and it is exactly the one that would
#      pass under the truncation bug — which is why A exists beside it.
#
#   C  a natural, non-air block in the first-poked chunk
#      Fails if our writer emits a structurally valid chunk that has lost its
#      contents — a blank column plus the sentinel would pass A and B and
#      leave the player's world deleted. Also catches palette and bit-packing
#      damage, since the position is chosen from a section with a non-trivial
#      palette.
#
# A and C are the pair. A alone passes on a writer that saves the edit into an
# empty world; C alone passes on a writer that never saved the edit, and on no
# writer at all. Only a writer that really wrote a real chunk passes both.
#
# There is deliberately NO arm asserting natural terrain in a chunk we never
# poked. It reads like the obvious way to prove the merge kept its neighbours,
# and it is precisely the arm that cannot fail: if the merge dropped that
# chunk, vanilla regenerates it from the same seed and reports the same block.
# The chunk-count assertion below tests that property with an instrument that
# can actually see it.
#
# THE NEGATIVE CONTROL, AND WHY IT IS A BYTE AND NOT A DELETION
#
# Until 2026-09-05 this gate had no control at all, and `docs/CI.md` recorded
# that as "three arms, A and C are the discriminating pair" — an argument
# about the arms' *structure*, which is not the same claim as "this gate has
# been shown going red". The structural argument is sound and it is not
# evidence.
#
# `--negative-control` runs the identical sequence and then flips **one byte
# inside the first-poked chunk's compressed stream**, after our writer has
# produced it and before vanilla is booted. That is the smallest injection
# that reaches the thing under test:
#
#   * deleting the region file would test whether vanilla regenerates a
#     missing world, which nobody doubts and this gate does not claim;
#   * truncating the file would fail at `region-differ scan` before vanilla
#     ran, so the arms would never be reached and a REFUSED would be recorded
#     as a control that fired;
#   * a byte inside the deflate stream leaves the header, the sector table and
#     every other chunk intact, so the *only* difference between the two arms
#     is whether chunk (64,64)'s payload survives. `RegionFile`'s read path
#     discards a chunk whose stream will not inflate and vanilla regenerates
#     it from the seed — which deletes the diamond sentinel and leaves the
#     natural terrain, so **arm A must fail and arm C must still pass**. A
#     control that took out both would be consistent with the gate having
#     stopped booting vanilla at all.
#
# The byte is chosen at the midpoint of the payload rather than at its start:
# the first two bytes are the zlib header, and corrupting those produces a
# different `RegionFile` complaint (`invalid chunk stream version`) that the
# gate would catch through the complaint check rather than through arm A. The
# arm is what is being controlled for, so the injection has to reach it.
#
# Usage: ci/t2-vanilla-loads-ours.sh [--negative-control]
#   T2VL_SEED   world seed, default 20260722
#   T2VL_PORT   port for both vanilla boots, default 25937 — and also, through
#               gen-vanilla-region.sh, the name of the fixture world
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
NEGATIVE=0
[ "${1:-}" = "--negative-control" ] && NEGATIVE=1
SEED="${T2VL_SEED:-20260722}"
# A port no other gate on this box uses: `gen-vanilla-region.sh` names its
# world directory `gen-<seed>-<port>`, so the port is this fixture's identity
# and a shared one means a shared world. See the fixture check below for what
# reusing another gate's world did.
PORT="${T2VL_PORT:-25937}"
CX=64; CZ=64; R=1

WORK="$ROOT/oracle-work/t2-vanilla-loads-ours"
SRC="$ROOT/oracle-work/gen-$SEED-$PORT"          # gen-vanilla-region.sh's world
RUN="$WORK/run"                                   # the copy we poke and boot
REGION="$RUN/world/dimensions/minecraft/overworld/region"
PROBE="$ROOT/target/debug/anvil-probe"
DIFFER="$ROOT/target/debug/region-differ"

fail() { echo "T2-VANILLA-LOADS-OURS RED — $*"; exit 1; }

cleanup() { "$ROOT/ci/vanilla-server.sh" stop "$RUN" >/dev/null 2>&1 || true; }
trap cleanup EXIT

command -v cargo >/dev/null 2>&1 || {
    echo "no cargo on PATH; over ssh prefix with: export PATH=\"\$HOME/.cargo/bin:\$PATH\"" >&2
    exit 2
}
cargo build -q -p anvil-probe -p region-differ || fail "could not build the instruments"

# --- 1. a vanilla-generated world to work in --------------------------------
#
# Generated by vanilla, not by us: the point is to modify a file vanilla
# itself wrote and hand it back, so the only thing under test is our writer.
# `gen-vanilla-region.sh` leaves its world behind at $SRC, whose name it
# derives from the seed and the port.
#
# **THE FIXTURE IS CHECKED FOR THE CHUNKS THIS GATE NEEDS, NOT FOR EXISTING.**
# The first version tested `[ -d .../region ]` and it silently reused a world
# another agent had left at the same seed-and-port two days earlier, generated
# around a different centre. Every region file was present and none of them
# held chunk (64,64) at full status, so the column this gate probes was air
# from bedrock to sky.
#
# That is worth spelling out, because it is the failure this gate's own
# structure was designed against and it arrived from an unexpected direction:
# the two sentinel arms **passed their pre-flight** on that empty column — of
# course they did, a sentinel is written against air — and had the gate been
# only "write a block, ask vanilla for it back", it would have gone green
# having proved nothing about a chunk with contents in it. Arm C is what
# refused, because it goes looking for real terrain and there was none.
WANT=$(((2 * R + 1) * (2 * R + 1)))
have_fixture() {
    local region="$1/world/dimensions/minecraft/overworld/region"
    [ -d "$region" ] || return 1
    local got
    got=$("$DIFFER" scan "$region" --bbox $((CX - R)) $((CZ - R)) $((CX + R)) $((CZ + R)) \
        2>/dev/null | grep -oP 'full=\K[0-9]+' || echo 0)
    [ "$got" -ge "$WANT" ]
}
if ! have_fixture "$SRC"; then
    echo "== no usable fixture at $SRC — generating (seed $SEED, centre $CX,$CZ, r=$R)"
    rm -rf "$SRC"
    "$ROOT/ci/gen-vanilla-region.sh" "$SEED" "$R" "$WORK/harvest" "$PORT" "$CX" "$CZ" \
        || fail "could not generate the vanilla world"
fi
have_fixture "$SRC" || fail \
    "$SRC still has fewer than $WANT full chunks in ($((CX - R)),$((CZ - R)))..($((CX + R)),$((CZ + R)))"

rm -rf "$RUN"; mkdir -p "$RUN"
cp -r "$SRC/world" "$RUN/world" || fail "could not copy the world"
# The lock belongs to the run that made it; vanilla rewrites it on boot.
rm -f "$RUN/world/session.lock"

# --- 2. pick the probe positions, and refuse if they are not discriminating -
#
# Chunk (64,64) and (65,65) both live in r.2.2 (64>>5 = 2), which is what makes
# arm A a test of the merge rather than of two independent files.
AX=$((CX * 16 + 8));  AZ=$((CZ * 16 + 8))          # chunk (64,64)
BX=$(((CX + 1) * 16 + 8)); BZ=$(((CZ + 1) * 16 + 8)) # chunk (65,65)
SY=200                                              # well above any terrain here

for pos in "$AX $SY $AZ" "$BX $SY $BZ"; do
    # shellcheck disable=SC2086
    got=$("$PROBE" get "$REGION" $pos) || fail "probe get failed at ($pos)"
    [ "$got" = "minecraft:air" ] || fail \
        "sentinel position ($pos) is already '$got', not air — a sentinel that \
is not written against air proves nothing"
done

# Arm C's position is DERIVED, not hardcoded. A hardcoded y that happened to
# be air would turn C into an assertion vanilla satisfies by regenerating, and
# nothing would say so. Walk down until a real, property-free block turns up.
CY=""
for y in 60 50 40 30 20 10 0 -10 -20 -30 -40 -50; do
    got=$("$PROBE" get "$REGION" "$AX" "$y" "$AZ") || continue
    case "$got" in
        minecraft:air|ABSENT|*"["*) continue ;;   # air, no section, or stateful
    esac
    CY="$y"; CBLOCK="$got"; break
done
[ -n "$CY" ] || fail "found no plain non-air block in chunk ($CX,$CZ) to use as arm C"
echo "== arm C: ($AX, $CY, $AZ) is $CBLOCK in the world vanilla generated"

BEFORE=$("$DIFFER" scan "$REGION" 2>/dev/null | grep -oP 'full=\K[0-9]+' || echo 0)
[ "$BEFORE" -gt 1 ] || fail "the region has $BEFORE chunks; the merge has nothing to preserve"

# --- 3. write, through our writer, twice into the same region file ----------
"$PROBE" poke "$REGION" "$AX" "$SY" "$AZ" "minecraft:diamond_block" \
    || fail "first poke failed"
"$PROBE" poke "$REGION" "$BX" "$SY" "$BZ" "minecraft:emerald_block" \
    || fail "second poke failed"

# The instrument that CAN see truncation, unlike any block assertion vanilla
# could make about a chunk it would regenerate identically.
AFTER=$("$DIFFER" scan "$REGION" 2>/dev/null | grep -oP 'full=\K[0-9]+' || echo 0)
[ "$AFTER" -eq "$BEFORE" ] || fail \
    "the region held $BEFORE chunks before the pokes and $AFTER after — the \
writer dropped chunks it was not asked to touch"
echo "== $AFTER chunks in the region before and after two merging writes"

# --- 3b. the control's injection --------------------------------------------
#
# One byte, at the midpoint of chunk ($CX,$CZ)'s compressed payload, in the
# file our writer has just produced. The offsets are `RegionFile`'s own
# layout, read from the class rather than remembered: a 4096-byte sector
# table of 1024 entries at 4 bytes each — three bytes of sector offset then
# one byte of sector count — indexed by `(x & 31) + (z & 31) * 32`; then a
# 4096-byte timestamp table; then, at `offset * 4096`, a big-endian i32
# length, one compression-type byte, and `length - 1` bytes of payload.
#
# The script REFUSES rather than continuing if it cannot find that payload.
# A control that silently injected nothing would run the gate unmodified and
# report the resulting GREEN as "the control did not fire", which is the
# opposite of what happened and is the exact shape of an unfalsifiable check.
if [ "$NEGATIVE" = 1 ]; then
    RF="$REGION/r.$((CX >> 5)).$((CZ >> 5)).mca"
    python3 - "$RF" "$CX" "$CZ" <<'INJECT' || fail "the control could not inject a byte"
import struct, sys
path, cx, cz = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
with open(path, "r+b") as f:
    f.seek(((cx & 31) + (cz & 31) * 32) * 4)
    entry = f.read(4)
    offset = int.from_bytes(entry[:3], "big")
    sectors = entry[3]
    if offset == 0 or sectors == 0:
        raise SystemExit(f"chunk ({cx},{cz}) is not allocated in {path}")
    f.seek(offset * 4096)
    (length,) = struct.unpack(">i", f.read(4))
    if length < 8:
        raise SystemExit(f"chunk ({cx},{cz}) declares a {length}-byte stream")
    # length counts the compression byte, so the payload is length - 1 and
    # starts at offset*4096 + 5. The midpoint keeps the zlib header intact.
    target = offset * 4096 + 5 + (length - 1) // 2
    f.seek(target)
    b = f.read(1)[0]
    f.seek(target)
    f.write(bytes([b ^ 0xFF]))
    print(f"   control: flipped byte at 0x{target:x} of chunk ({cx},{cz}), "
          f"{length - 1}-byte payload at sector {offset}")
INJECT
fi

# --- 4. boot REAL vanilla on it and ask ------------------------------------
"$ROOT/ci/vanilla-server.sh" start "$RUN" "$PORT" "minecraft:normal" "$SEED" \
    || fail "vanilla would not boot on the world we wrote"
LOG="$RUN/server.log"

"$ROOT/ci/vanilla-server.sh" console "$RUN" "tick freeze"
"$ROOT/ci/vanilla-server.sh" console "$RUN" \
    "forceload add $((AX - 16)) $((AZ - 16)) $((BX + 16)) $((BZ + 16))"
sleep 5

"$ROOT/ci/vanilla-server.sh" console "$RUN" \
    "execute if block $AX $SY $AZ minecraft:diamond_block run say ARM_A_SENTINEL_IN_FIRST_CHUNK"
"$ROOT/ci/vanilla-server.sh" console "$RUN" \
    "execute if block $BX $SY $BZ minecraft:emerald_block run say ARM_B_SENTINEL_IN_SECOND_CHUNK"
"$ROOT/ci/vanilla-server.sh" console "$RUN" \
    "execute if block $AX $CY $AZ $CBLOCK run say ARM_C_TERRAIN_SURVIVED"
# A command vanilla must answer AFTER the three above, so that "no marker in
# the log" cannot be confused with "the console never got that far". Without
# it a fifo that silently stopped delivering looks identical to three failed
# predicates.
"$ROOT/ci/vanilla-server.sh" console "$RUN" "say ALL_QUERIES_DELIVERED"
sleep 5

"$ROOT/ci/vanilla-server.sh" stop "$RUN"

grep -q "ALL_QUERIES_DELIVERED" "$LOG" || fail \
    "vanilla never reported the trailing marker — the console did not deliver, \
so the arms below measured nothing"

MISSING=""
grep -q "ARM_A_SENTINEL_IN_FIRST_CHUNK"  "$LOG" || MISSING="$MISSING A"
grep -q "ARM_B_SENTINEL_IN_SECOND_CHUNK" "$LOG" || MISSING="$MISSING B"
grep -q "ARM_C_TERRAIN_SURVIVED"         "$LOG" || MISSING="$MISSING C"

# --- the control's verdict, which is the opposite of the gate's -------------
#
# Three things are asserted, not one, and the second and third are what stop
# this being "the gate went red, therefore the control fired":
#
#   * arm A must be MISSING — the sentinel is gone with the chunk;
#   * arm C must be PRESENT — vanilla regenerated that chunk from the seed
#     rather than failing to boot or serving air, so the injection reached
#     the payload and nothing else;
#   * vanilla must have COMPLAINED about the stream, in its own words, which
#     is the direct evidence that the byte is what did it.
#
# A control that satisfied only the first would also be satisfied by vanilla
# never starting.
if [ "$NEGATIVE" = 1 ]; then
    case "$MISSING" in
        *A*) ;;
        *) fail "NEGATIVE CONTROL FAILED — arm A still found the sentinel in a \
chunk whose compressed stream we corrupted, so arm A is not reading our bytes" ;;
    esac
    case "$MISSING" in
        *C*) fail "NEGATIVE CONTROL FAILED — arm C went too: the injection did \
more than damage one chunk's payload, so this is not a control for arm A" ;;
    esac
    if ! grep -qE "stream is truncated|invalid chunk stream version|is allocated, but stream is missing|Failed to (check|load|read)|error in chunk|ERROR.*chunk" "$LOG"; then
        echo "-- what vanilla actually said:"
        grep -iE "chunk|region" "$LOG" | tail -10
        fail "NEGATIVE CONTROL FAILED — arm A went red but vanilla logged no \
complaint about the region file, so the byte may not be why"
    fi
    echo "T2-VANILLA-LOADS-OURS CONTROL GREEN — one flipped byte took arm A \
red and left arm C green, and vanilla said why"
    exit 0
fi

# Vanilla is loud about a region file it dislikes, and those messages are the
# diagnosis when an arm fails — surface them rather than making the next
# reader go looking.
if [ -n "$MISSING" ]; then
    echo "-- vanilla's own complaints, if any:"
    grep -iE "invalid sector|truncated|not present|Failed to (check|load|read)|chunk stream|ERROR" \
        "$LOG" | head -10
    fail "vanilla did not confirm arm(s):$MISSING  (log: $LOG)"
fi

# Loading it is not the same as being happy with it, and the three arms above
# cannot tell the difference.
#
# `RegionFile`'s read path recovers from most damage by discarding the chunk
# and logging: a sector that overlaps the header, a declared size past the end
# of the file, a truncated deflate stream. Vanilla then regenerates that
# chunk. For the two sentinel chunks that shows up as a failed arm — but for
# any OTHER chunk in the region it is invisible, because a chunk regenerated
# from the same seed is the chunk that was there. So a writer that corrupted
# 48 of the 50 chunks and got the two sentinels right would pass every
# assertion above.
#
# The strings are `RegionFile`'s own, read out of the class's constant pool
# (`javap -p -c -constants`), rather than guessed at:
#
#   "Region file {} has truncated header: {}"
#   "... has invalid sector at index: {}; sector {} overlaps with header"
#   "... has an invalid sector at index: {}; size has to be > 0"
#   "... has an invalid sector at index: {}; sector {} is out of bounds"
#   "Chunk {} header is truncated: expected {} but read {}"
#   "Chunk {} is allocated, but stream is missing"
#   "Chunk {} stream is truncated: expected {} but read {}"
#   "Declared size {} of chunk {} is negative"
#   "Chunk {} has invalid chunk stream version {}"
COMPLAINTS=$(grep -cE \
    "has truncated header|invalid sector at index|is allocated, but stream is missing|\
header is truncated|stream is truncated|is negative|invalid chunk stream version" \
    "$LOG" || true)
if [ "$COMPLAINTS" -ne 0 ]; then
    echo "-- what vanilla said about our region file:"
    grep -E "has truncated header|invalid sector at index|is allocated, but stream is missing|\
header is truncated|stream is truncated|is negative|invalid chunk stream version" \
        "$LOG" | head -10
    fail "vanilla read the sentinels but logged $COMPLAINTS region-file \
complaint(s) — some other chunk in the region was damaged and silently \
regenerated  (log: $LOG)"
fi

echo "T2-VANILLA-LOADS-OURS GREEN — vanilla read our region: sentinel in the \
first-poked chunk, sentinel in the second, and the original terrain, all three"
