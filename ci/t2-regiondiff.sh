#!/usr/bin/env bash
# T2-regiondiff — prove the Anvil parser + differ end-to-end BEFORE rustmc
# has worldgen: generate the same seed twice with real vanilla, diff the
# inner square, demand bit-exact 100.000000%. If vanilla-vs-vanilla isn't
# 100%, the parser/differ/gen-harness is broken — fix that, never the
# tolerance (CI.md zero-flake rules).
#
# THAT PREMISE IS FALSE AND THE 100% HOLDS ONLY FOR THE PAIR ALREADY ON DISK
# — measured 2026-08-16, branch worldgen-block-entities, and recorded here
# rather than acted on. The frozen fixture at `oracle-work/t2-regiondiff/`
# reads EXACTNESS 100.000000%. Regenerating the pair from scratch at the same
# seed, radius and 3x3 comparison gives 17 mismatches, 99.998079%, in
# `sulfur_spike` and `air`. So this script goes RED on any fresh harvest, and
# its green is a property of an input that stopped changing.
#
# The header above was written before this project had worldgen, and every
# floor measured since contradicts it: vanilla disagrees with itself by 3,006
# blocks on the r=7 overworld window, 252 in the End, and 0..13 block entities
# on the seed-12345 r=16 one (`docs/DETERMINISM.md` §40). A vanilla-vs-vanilla
# reading below 100% is vanilla's own decoration-order noise, not a broken
# parser.
#
# NOTHING IS CHANGED HERE. This script is in neither `ci/t0.sh` nor
# `ci/t1.sh` nor `ci/handoff.sh`, so it gates nothing today, and
# `oracle-work/t2-regiondiff/` survives as the fixture for
# `real_vanilla_chunks_survive_a_rewrite`. Adjusting a threshold on a shared
# artefact needs its own item and its own measurement of what the threshold
# should be. `docs/DETERMINISM.md` §41.3; `ci/figures.toml`
# `t2-regiondiff-fresh-pair-floor`.
# T2-regiondiff — the Anvil parser and the differ, in three named parts.
#
#     ./ci/t2-regiondiff.sh
#
# # What was wrong with the old form, and it is this project's central defect
#
# The old script harvested the same window from vanilla twice and demanded
# `EXACTNESS 100.000000%`. Two things about that, both measured 2026-08-16 and
# written up in `docs/DETERMINISM.md` §36 and §37:
#
# 1. **Its green could not be turned red by any defect in the thing it is named
#    for.** Both sides were read by the same parser and compared by the same
#    differ, and the assertion was that they *agree*. A differ that returns zero
#    mismatches for every input passes it. A parser that reads every chunk as
#    empty passes it. It was a harvest-reproducibility check wearing the name
#    "Anvil parser+differ determinism proof" — the instrument the parity figures
#    are produced with, certified by a check that could not fail.
#
# 2. **The property it did assert is false.** Eight harvests of its own window
#    produce five distinct worlds; 24 of the 28 pairs are non-zero, spanning
#    0..536 blocks of 884,736. The 100.000000% in `docs/ORACLE.md` was one lucky
#    pair, exactly as the End's published zero was (§5). The script also wrote
#    its harvests straight into `oracle-work/t2-regiondiff/{a,b}` with `rm -rf`
#    — the shared read-only fixture `crates/rustmc-world`'s round-trip test
#    reads and `ci/handoff.sh` stage 1 links every gate directory from — so
#    running it destroyed the fixture for every tree on the box. That is why
#    nobody ran it, and why it fossilised: its last real execution was
#    2026-07-22.
#
# # What replaces it
#
# Three parts with three different jobs, named separately so that no one of them
# can stand in for another. A frozen known-answer test is a legitimate thing to
# have — it is the only way to pin a *parser* — but it is not a determinism
# proof, and the old script let one wear the other's name.
#
#   REGIONDIFF-KAT      Known-answer. The frozen 2026-07-22 fixture, READ ONLY,
#                       never regenerated by this script. Pins what the parser
#                       must decode out of real vanilla bytes: chunk count,
#                       denominator, a block census that requires correct
#                       palette decoding and bit-unpacking, and a self-diff of
#                       zero. Red when the parser mis-reads a chunk.
#
#   REGIONDIFF-CONTROL  The differ's positive control, on LIVE input. A chunk is
#                       removed from a copy of one side by
#                       `ci/regiondiff-drop-chunk.py`, which edits the Anvil
#                       location table with `struct.unpack` and shares no code
#                       with our parser. The effect is exact arithmetic the
#                       differ itself supplied a moment earlier: the denominator
#                       must fall by exactly one chunk's blocks and the mismatch
#                       count by exactly that chunk's own contribution. Red when
#                       the differ mis-counts.
#
#   REGIONDIFF-LIVE     The determinism half, and it is genuinely live: two
#                       fresh vanilla harvests taken by this run, of input that
#                       can and does change. Demands 100.000000%.
#
# # Why REGIONDIFF-LIVE can demand 100% when §36 says the window has a floor
#
# Because it sets the knob §37 found. The floor is not vanilla's decoration
# order here — it is **concurrency**. `Util.maxAllowedExecutorThreads()` is
# `Mth.clamp(availableProcessors() - 1, 1, getMaxThreads())` and `ChunkMap`
# dispatches every chunk status upgrade onto that pool, so which chunk reaches
# FEATURES first is a race, and features write one chunk out. Clamped to a
# single worker with `-Dmax.bg.threads=1` — a system property the unmodified
# server reads for itself, no jar patching — most of the variance goes: four
# runs, six pairs, all 0 of 884,736.
#
# **AND THAT IS TRUE HERE BECAUSE OF THE EXTENT, WHICH IS WORTH STATING —
# `docs/DETERMINISM.md` §39.** The clamp is exact over the INTERIOR OF A SMALL
# HARVEST and not in general: at a 1,089-chunk extent it leaves 15 of 15 pairs
# non-zero (§38), and even at this extent it leaves a second world in the
# boundary ring outside this window. This gate reads the inner 9 chunks of a
# small harvest, which is exactly the regime where the clamp is exact, and that
# was measured on THIS window rather than assumed: four independent clamped
# harvests of seed 20260722 at r=2 agree on all six pairs over `63 63 65 65`,
# while three unclamped ones disagree by 10, 17 and 27. Re-measure with
# `ci/clamp-extent-control.sh EXTENT_SEED=20260722` before widening this gate's
# window or its extent — neither is free, and the property does not survive
# either change.
# server reads for itself, no jar patching — the harvest is bit-reproducible:
# four runs, six pairs, all 0 of 884,736.
#
# **So this part's green is turnable red by one word, and that is its evidence:
# delete `-Dmax.bg.threads=1` and it goes red on 24 of 28 pairs.**
# `ci/regiondiff-falsify.sh` runs that arm, plus injected parser and differ
# faults against the other two parts.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SEED="${T2_SEED:-20260722}"
R=2                      # 5x5 chunk square; inner margin 1 -> compare 3x3
BBOX=(--bbox 63 63 65 65)
DIFFER="$ROOT/target/debug/region-differ"
FAIL=0

# The frozen known-answer fixture. READ ONLY. Nothing in this script writes
# here — see the header for what the old script's `rm -rf` on this path cost.
KAT="$ROOT/oracle-work/t2-regiondiff/a"

# The live half harvests into a private per-run directory that nothing else on
# the box reads, so two trees running this at once cannot overwrite each other
# and neither can touch the shared fixture.
LIVE="${T2_REGIONDIFF_LIVE_DIR:-$ROOT/oracle-work/regiondiff-live-$$}"

if command -v cargo >/dev/null 2>&1; then
    cargo build -q -p region-differ
elif [ ! -x "$DIFFER" ]; then
    echo "no cargo on PATH and no prebuilt $DIFFER" >&2
    echo "over ssh, prefix with: export PATH=\"\$HOME/.cargo/bin:\$PATH\"" >&2
    exit 2
fi

say()  { printf '%s\n' "$*"; }
ok()   { printf '  ok   %s\n' "$*"; }
bad()  { printf '  FAIL %s\n' "$*"; FAIL=1; }

# `want <label> <got> <expected>` — an equality with both sides printed. A
# control that says only "FAIL" makes the next agent re-derive the numbers.
want() {
    if [ "$2" = "$3" ]; then ok "$1 = $2"; else bad "$1: got $2, want $3"; fi
}

field() {  # field <text> <key>  — pull `key=<digits>` out of differ output
    printf '%s' "$1" | grep -oP "\\b$2=\\K[0-9]+" | head -1 || true
}

# =============================================================================
# PART 1 — REGIONDIFF-KAT: the parser against a known answer
# =============================================================================
#
# Every number below was read off the 2026-07-22 fixture and is a fact about
# those bytes, not about any run. They are pinned rather than recomputed because
# a known-answer test that derives its answer from the thing under test is the
# defect this whole file exists to stop repeating.
#
# The census is the load-bearing one. `chunks` and `blocks` would survive a
# parser that decoded geometry and threw the contents away; a per-block-type
# count cannot, because producing it requires resolving each section's palette
# and unpacking the block-state array at the right bit width. The fixture's
# palettes run to 19 entries, so the packed path is genuinely exercised.
say "== REGIONDIFF-KAT — known answer, frozen fixture, read only =="
if [ ! -d "$KAT" ]; then
    echo "REGIONDIFF-KAT REFUSED — no fixture at $KAT" >&2
    echo "  It is Mojang-derived and gitignored. It lives in the shared reference" >&2
    echo "  directory ci/handoff.sh stage 1 links every gate directory from." >&2
    echo "  This script does NOT regenerate it: it is a known answer, and a known" >&2
    echo "  answer this script could rewrite would not be one." >&2
    exit 2
fi

KAT_SCAN=$("$DIFFER" scan "$KAT" "${BBOX[@]}")
want "KAT full chunks" "$(field "$KAT_SCAN" full)" 9

KAT_CENSUS=$("$DIFFER" census "$KAT" "${BBOX[@]}" --match stone)
want "KAT census chunks" "$(field "$KAT_CENSUS" chunks)" 9
want "KAT census blocks" "$(field "$KAT_CENSUS" blocks)" 884736
for pair in "minecraft:stone 32824" "minecraft:cobblestone 77" \
            "minecraft:deepslate_redstone_ore 54" "minecraft:mossy_cobblestone 51" \
            "minecraft:redstone_ore 4" "minecraft:sandstone 1"; do
    set -- $pair
    got=$(printf '%s' "$KAT_CENSUS" | awk -v b="$1" '$2 == b {print $1}' | head -1 || true)
    want "KAT census $1" "${got:-absent}" "$2"
done

# A directory diffed against itself must be empty of mismatches over the whole
# denominator. This is the one assertion the OLD gate could also make, and on
# its own it is worth little — it is here because it costs nothing and it pins
# the denominator on the diff path as well as the census path.
KAT_SELF=$("$DIFFER" diff "$KAT" "$KAT" "${BBOX[@]}")
want "KAT self-diff blocks"     "$(field "$KAT_SELF" blocks)" 884736
want "KAT self-diff mismatches" "$(field "$KAT_SELF" mismatches)" 0

# --- the differ's known answer, and why a THIRD reference had to be made ----
#
# Everything above this line is satisfied by a differ that reports zero
# mismatches for every input, and so is the live half — under
# `-Dmax.bg.threads=1` the two fresh harvests genuinely agree, so "0" is the
# right answer there and an always-zero differ gives it. `a` and `b` agree
# exactly too. **No pair of directories this gate had could catch a differ that
# had stopped counting.**
#
# **The pair used for it is `vanilla-r7` and its twin `vanilla-r7-b`, and the
# choice is the correction of a real defect in the first version of this gate.**
#
# That version made a *new* reference, `oracle-work/t2-regiondiff/c`, pinned at
# 407 blocks. It was correct arithmetic and the wrong design: `oracle-work` is
# gitignored, so `c/` existed only in the tree that made it. At the merge gate
# of 2026-08-16 20:43 the branch's own T0 refused it — `~/rustmc/oracle-work`,
# the shared directory `ci/handoff.sh` stage 1 links every gate directory from,
# had no `c/`, so this block exited 2 *before* the assertion it exists to make,
# and `ci/regiondiff-falsify.sh` arm 2 reported red-for-the-wrong-reason. A
# check whose fixture is not where the gate reads is the
# `real_vanilla_chunks_survive_a_rewrite` defect exactly, and it was reproduced
# here inside the repair for it.
#
# `vanilla-r7` and `vanilla-r7-b` need nothing installed: they are the
# project's oldest twinned overworld pair, already load-bearing for the worldgen
# tests, already in the shared reference directory on every box. And being a
# *twin* pair they are guaranteed to disagree — that disagreement is the r=7
# overworld floor this project quotes (`docs/AGENT-BRIEF.md`), so a zero here
# would itself be a finding. Pinned over an explicit window because a floor
# belongs to the pair of runs that produced it: 823 blocks of 2,654,208 over
# `--bbox 60 60 68 68 --ybox 0 127`, vanilla first.
KATT="$ROOT/oracle-work/vanilla-r7"
KATT_B="$ROOT/oracle-work/vanilla-r7-b"
if [ ! -d "$KATT" ] || [ ! -d "$KATT_B" ]; then
    echo "REGIONDIFF-KAT REFUSED — no twinned reference pair at" >&2
    echo "    $KATT" >&2
    echo "    $KATT_B" >&2
    echo "  Without a pair that DISAGREES, nothing in this gate can fail on a" >&2
    echo "  differ that reports zero mismatches for every input — a/ and b/ agree" >&2
    echo "  exactly and so does the clamped live pair, so zero is the right answer" >&2
    echo "  everywhere else here. These two are Mojang-derived and gitignored;" >&2
    echo "  they live in the shared reference directory ci/handoff.sh stage 1" >&2
    echo "  links every gate directory from. Link them in, do not regenerate them." >&2
    exit 2
fi
TWIN_BBOX=(--bbox 60 60 68 68 --ybox 0 127)
KAT_DIFF=$("$DIFFER" diff "$KATT" "$KATT_B" "${TWIN_BBOX[@]}")
want "KAT differ blocks"     "$(field "$KAT_DIFF" blocks)" 2654208
want "KAT differ mismatches" "$(field "$KAT_DIFF" mismatches)" 823
# The count alone would survive a differ that found 823 of the wrong things.
# These rows say it found the right ones — the vegetation the r=7 floor is made
# of, which is the read-before-write class §36 names.
for row in "minecraft:water[level=0] minecraft:seagrass 107" \
           "minecraft:water[level=0] minecraft:kelp_plant 98" \
           "minecraft:seagrass minecraft:water[level=0] 95"; do
    set -- $row
    got=$(printf '%s' "$KAT_DIFF" | awk -v x="$1" -v y="$2" \
        '$2 == x && $3 == "->" && $4 == y {print $1}' | head -1 || true)
    want "KAT differ row $1 -> $2" "${got:-absent}" "$3"
done

# =============================================================================
# PART 2 + 3 — the live halves
# =============================================================================
#
# `T2_REGIONDIFF_LIVE_DIR` pointing at a directory that already holds `a/` and
# `b/` reuses them instead of harvesting. That exists for
# `ci/regiondiff-falsify.sh`, which has to run this gate many times against
# injected faults and must not boot vanilla twice for each — NOT as a way to
# skip the harvest in a real run. A real run leaves the flag unset, and the
# `HARVEST-ORDER` stamps this script prints say which happened.
if [ -d "$LIVE/a" ] && [ -d "$LIVE/b" ]; then
    say "== live pair supplied at $LIVE (no harvest this run) =="
else
    say "== harvesting a fresh live pair (2 vanilla boots, -Dmax.bg.threads=1) =="
    mkdir -p "$LIVE"
    # ONE background worker. This is the knob, and the reason is in the header:
    # without it these two harvests agree only about 1 time in 7.
    export VANILLA_JVM_OPTS="${VANILLA_JVM_OPTS:--Dmax.bg.threads=1}"
    "$ROOT/ci/gen-vanilla-region.sh" "$SEED" "$R" "$LIVE/a" "${T2_PORT_A:-25701}" 64 64
    "$ROOT/ci/gen-vanilla-region.sh" "$SEED" "$R" "$LIVE/b" "${T2_PORT_B:-25702}" 64 64
fi

LIVE_DIFF=$("$DIFFER" diff "$LIVE/a" "$LIVE/b" "${BBOX[@]}")
LIVE_BLOCKS=$(field "$LIVE_DIFF" blocks)
LIVE_MIS=$(field "$LIVE_DIFF" mismatches)

say "== REGIONDIFF-CONTROL — the differ, against a mutation with a known answer =="
# Pick the chunk that contributes the MOST mismatches, so the control moves the
# mismatch count as well as the denominator. On a pair that happens to agree
# everywhere the differ prints no `worst chunk` line at all and the expected
# mismatch delta is 0 — still a valid control on the denominator, and the script
# says which case it is rather than quietly asserting less.
WORST=$(printf '%s' "$LIVE_DIFF" | grep -oP '^\s+worst chunk \(\K[-0-9]+,[-0-9]+' | head -1 || true)
WORST_N=$(printf '%s' "$LIVE_DIFF" | grep -oP '^\s+worst chunk \([-0-9]+,[-0-9]+\): \K[0-9]+' | head -1 || true)
if [ -z "$WORST" ]; then WORST="64,64"; WORST_N=0; fi
CX="${WORST%,*}"; CZ="${WORST#*,}"

MUT="$LIVE/b-mutant"
rm -rf "$MUT"; cp -r "$LIVE/b" "$MUT"
# Exits 2 if the chunk was already absent — a mutation that changed nothing
# would make this control pass for the wrong reason.
python3 "$ROOT/ci/regiondiff-drop-chunk.py" "$MUT" "$CX" "$CZ" \
    || { echo "REGIONDIFF-CONTROL REFUSED — the mutation did not apply" >&2; exit 2; }

MUT_DIFF=$("$DIFFER" diff "$LIVE/a" "$MUT" "${BBOX[@]}")
# 16 x 16 x 384 = 98,304 blocks in one chunk of this window, and 4 x 4 x 96 =
# 1,536 biome cells. Both are geometry, not content, so they are constants.
want "CONTROL blocks after dropping ($CX,$CZ)" \
     "$(field "$MUT_DIFF" blocks)"     "$((LIVE_BLOCKS - 98304))"
want "CONTROL mismatches after dropping ($CX,$CZ)" \
     "$(field "$MUT_DIFF" mismatches)" "$((LIVE_MIS - WORST_N))"
want "CONTROL comparable chunks" "$(field "$MUT_DIFF" chunks)" 8
rm -rf "$MUT"

say "== REGIONDIFF-LIVE — two fresh harvests of input that can change =="
say "$LIVE_DIFF" | head -1
want "LIVE blocks"      "$LIVE_BLOCKS" 884736
want "LIVE mismatches"  "$LIVE_MIS"    0
if printf '%s' "$LIVE_DIFF" | grep -c "EXACTNESS 100.000000%" >/dev/null; then
    ok "LIVE exactness = 100.000000%"
else
    bad "LIVE exactness: $(printf '%s' "$LIVE_DIFF" | grep -o 'EXACTNESS.*')"
    echo "       Two vanilla harvests of one seed and window disagree. Under" >&2
    echo "       -Dmax.bg.threads=1 that should not happen AT THIS EXTENT AND" >&2
    echo "       THIS WINDOW (DETERMINISM.md §37, and §39 for why the extent is" >&2
    echo "       part of the condition: four clamped r=2 harvests agree on all" >&2
    echo "       six pairs here, but at r=16 all fifteen disagree)." >&2
    echo "       1. Check the clamp actually took -- read bg_threads=1 back off" >&2
    echo "          each HARVEST-ORDER rather than trusting the invocation." >&2
    echo "       2. Check nothing widened this gate's window or its harvest" >&2
    echo "          extent: the exactness is a property of the inner 9 chunks of" >&2
    echo "          a SMALL harvest, and does not survive either being grown." >&2
    echo "       3. Only then suspect the parser: unclamped, this window's floor" >&2
    echo "          is 0..536 blocks and 24 of 28 pairs are non-zero (§36)." >&2
    echo "       -Dmax.bg.threads=1 that should not happen (DETERMINISM.md §37:" >&2
    echo "       four runs, six pairs, all 0). Check the clamp actually took" >&2
    echo "       before suspecting the parser: without it this window's floor is" >&2
    echo "       0..536 blocks and 24 of 28 pairs are non-zero (§36)." >&2
fi

[ -n "${T2_REGIONDIFF_LIVE_DIR:-}" ] || rm -rf "$LIVE"

if [ "$FAIL" -ne 0 ]; then echo "T2-REGIONDIFF RED"; exit 1; fi
echo "T2-REGIONDIFF GREEN  (KAT + CONTROL + LIVE)"
